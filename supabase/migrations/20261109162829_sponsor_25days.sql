CREATE OR REPLACE FUNCTION public.sponsor_admin_overview()
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
BEGIN
  IF NOT COALESCE(public.has_role((SELECT auth.uid()), 'admin'::app_role), false) THEN
    RAISE EXCEPTION 'not_authorized' USING ERRCODE = '42501';
  END IF;
  PERFORM public.sponsor_require_admin();  -- the admin check again, plus the switch
  RETURN jsonb_build_object(
    'signups', COALESCE((SELECT jsonb_agg(to_jsonb(s) - 'updated_at' || jsonb_build_object(
                          'days', COALESCE((SELECT jsonb_agg(d.day ORDER BY d.day) FROM public.sponsor_days d WHERE d.signup_id = s.id), '[]'::jsonb))
                          ORDER BY s.created_at DESC)
                          FROM public.sponsor_signups s), '[]'::jsonb),
    'invites', COALESCE((SELECT jsonb_agg(jsonb_build_object(
                          'id', i.id, 'brand', i.brand, 'email', i.email, 'ref_code', i.ref_code, 'created_at', i.created_at,
                          'visits', (SELECT count(*) FROM public.sponsor_visits v WHERE v.ref_code = i.ref_code),
                          'first_visit', (SELECT min(v.visited_at) FROM public.sponsor_visits v WHERE v.ref_code = i.ref_code),
                          'last_visit', (SELECT max(v.visited_at) FROM public.sponsor_visits v WHERE v.ref_code = i.ref_code),
                          'signed_up', EXISTS (SELECT 1 FROM public.sponsor_signups s WHERE s.ref_code = i.ref_code))
                          ORDER BY i.created_at DESC)
                          FROM public.sponsor_invites i), '[]'::jsonb),
    'testimonials', COALESCE((SELECT jsonb_agg(to_jsonb(t) ORDER BY t.created_at DESC) FROM public.sponsor_testimonials t), '[]'::jsonb),
    'settings', (SELECT to_jsonb(st) - 'id' - 'updated_at' FROM public.sponsor_settings st WHERE st.id),
    'directVisits', (SELECT count(*) FROM public.sponsor_visits v WHERE v.ref_code IS NULL)
  );
END;
$function$;

