#!/usr/bin/env node
/**
 * Prerender the pages whose text must be in the raw HTML (src/prerender/staticPages.tsx: /terms/full,
 * /privacy/full, /sms-opt-in; owner/lead 2026-10-23, Twilio's A2P checker runs no JavaScript).
 *
 * Loads the app's own components through Vite's SSR loader (same config, aliases and env as the build), renders
 * each page body to static markup, checks the required text is there (fails the build if not), and writes
 * scripts/generated/static-pages.js, which api/share.ts imports and places inside #root for those routes.
 * Gitignored like og-shell.js (scripts/generated/). Wired into `npm run build`.
 *
 *   node scripts/prerender-static-pages.mjs            # write the module
 *   node scripts/prerender-static-pages.mjs --print    # also print each page's size and first line of text
 */
import { mkdir, writeFile, rename } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createServer } from "vite";
import { existsSync, readFileSync } from "node:fs";
import { gzipSync } from "node:zlib";
import { guideShellData, FIRST_SCREEN_ITEMS } from "./lib/guideShellBuild.mjs";
import { DEAL_DAY_SLUGS } from "../src/content/giftGuideDeals.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outPath = path.join(root, "scripts", "generated", "static-pages.js");
// SEO P1 (owner 11-19): the gift guides' names, picks, groups and moved slugs for api/share.ts's per-page bodies and
// 404s (src/prerender/seoData.ts, src/lib/seoBodies.mjs). Gitignored like static-pages.js.
const seoOutPath = path.join(root, "scripts", "generated", "seo-data.js");
// Guide prerender (11-24, owner rule: pages under 2 s): each live guide page's first screen and its rules, for
// api/share.ts to draw inside #boot-loader (src/lib/guideShell.mjs). Gitignored like static-pages.js and rebuilt from
// the guide data on every build, so it cannot go stale against it.
const guideOutPath = path.join(root, "scripts", "generated", "guide-shells.js");

// A minimal config, not vite.config.ts: that file aliases react/react-dom to absolute file paths (one React for the
// browser bundle), which makes Vite's SSR loader inline React's CommonJS as ESM and fail. Here React stays a plain
// external dependency of Node. The "@" alias, the JSX runtime and the build-time defines match the app's.
// React Router's <Link> warns about useLayoutEffect once per link on a server render, and the Supabase client
// warns that a dev server points at prod. Both are harmless here (static markup, no queries run) and are left in
// the log: a console wrapper that forwards arbitrary arguments is a clear-text-logging sink (CodeQL).
const server = await createServer({
  root,
  mode: "production",
  configFile: false,
  // The guide pages render once per width: useIsMobile reads what src/prerender/guidePages.tsx sets (useIsMobileStub.ts).
  resolve: {
    alias: [
      { find: /^@\/hooks\/use-mobile$/, replacement: path.join(root, "src", "prerender", "useIsMobileStub.ts") },
      { find: "@", replacement: path.join(root, "src") },
    ],
  },
  esbuild: { jsx: "automatic" },
  define: { __APP_COMMIT__: JSON.stringify("prerender"), __APP_BUILT_AT__: JSON.stringify(""), __APP_COMMIT_FULL__: JSON.stringify("prerender") },
  logLevel: "error",
  appType: "custom",
  server: { middlewareMode: true, hmr: false, watch: null },
  optimizeDeps: { noDiscovery: true, include: [] },
});
let pages;
let gaps;
let seoData;
let guidePages;
try {
  const mod = await server.ssrLoadModule("/src/prerender/staticPages.tsx");
  pages = mod.renderStaticPages();
  gaps = mod.staticPageGaps(pages);
  seoData = await (await server.ssrLoadModule("/src/prerender/seoData.ts")).buildSeoData();
  guidePages = await (await server.ssrLoadModule("/src/prerender/guidePages.tsx")).renderGuidePages();
} finally {
  await server.close();
}
if (gaps.length) {
  console.error(`prerender-static-pages: the raw HTML would be missing required text:\n  ${gaps.join("\n  ")}`);
  process.exit(1);
}
await mkdir(path.dirname(outPath), { recursive: true });
const tmp = `${outPath}.${process.pid}.tmp`;
await writeFile(
  tmp,
  "// GENERATED by scripts/prerender-static-pages.mjs from src/prerender/staticPages.tsx. Do not edit.\n" +
    `export const STATIC_PAGE_BODIES = ${JSON.stringify(pages)};\n`,
);
await rename(tmp, outPath);
const guideCount = Object.keys(seoData?.guides ?? {}).length;
// 2026-11-21: only Her, Him, Kids and the 25 Days sponsors page are live (owner), and the catalog keeps 14 entries
// (measured in CI on 2026-11-21; 54 on 2026-11-20). Fewer than the 4 live pages means the catalog failed to load.
if (guideCount < 4) {
  console.error(`prerender-static-pages: the gift guide SEO data holds ${guideCount} guides (expected 14 on 2026-11-21)`);
  process.exit(1);
}
const seoTmp = `${seoOutPath}.${process.pid}.tmp`;
await writeFile(
  seoTmp,
  "// GENERATED by scripts/prerender-static-pages.mjs from src/prerender/seoData.ts. Do not edit.\n" +
    `export const SEO_DATA = ${JSON.stringify(seoData)};\n`,
);
await rename(seoTmp, seoOutPath);
console.log(`prerender-static-pages: seo-data ${guideCount} guides`);
for (const [p, html] of Object.entries(pages)) {
  console.log(`prerender-static-pages: ${p} ${html.length} bytes`);
}

// The app sheet the guide first screens' rules come from (the build's async stylesheet). Run without a build (no
// dist/), the pages are written with no rules and api/share.ts draws none of them (withGuideShell needs the rules).
const distIndex = path.join(root, "dist", "index.html");
let appCss = null;
if (existsSync(distIndex)) {
  const hrefs = [...readFileSync(distIndex, "utf8").matchAll(/<link rel="stylesheet" href="(\/assets\/[^"]+\.css)"[^>]*data-async-css>/g)].map((m) => m[1]);
  if (hrefs.length) appCss = hrefs.map((h) => readFileSync(path.join(root, "dist", h), "utf8")).join("\n");
}
const { data: guideData, counts } = guideShellData(guidePages, appCss);
// A guide (and the landing's Top 10) opens on at least 4 gifts; a deals day on at least one line (Small Business
// Saturday's shop grid is read live from the database, so its first screen is its banner and its one static row).
const short = Object.entries(counts).filter(([p, n]) => n < (DEAL_DAY_SLUGS.includes(p.replace("/gift-guides/", "")) ? 1 : Math.min(4, FIRST_SCREEN_ITEMS)));
if (short.length) {
  console.error(`prerender-static-pages: guide first screens with almost no items: ${short.map(([p, n]) => `${p} ${n}`).join(", ")}`);
  process.exit(1);
}
const guideTmp = `${guideOutPath}.${process.pid}.tmp`;
await writeFile(
  guideTmp,
  "// GENERATED by scripts/prerender-static-pages.mjs from src/prerender/guidePages.tsx. Do not edit.\n" +
    `export const GUIDE_SHELLS = ${JSON.stringify(guideData)};\n`,
);
await rename(guideTmp, guideOutPath);
console.log(`prerender-static-pages: guide shells css ${guideData.css ? `${guideData.css.length} B (${gzipSync(guideData.css).length} B gz)` : "none (no dist/)"}`);
for (const [p, b] of Object.entries(guideData.pages)) console.log(`prerender-static-pages: guide ${p} ${counts[p]} items, ${b.length} B (${gzipSync(b).length} B gz)`);
