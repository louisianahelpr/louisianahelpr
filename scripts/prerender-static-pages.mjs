#!/usr/bin/env node
/**
 * Prerender the pages whose text must be in the raw HTML (src/prerender/staticPages.tsx: /terms/full,
 * /privacy/full, /sms-opt-in; owner/lead 2026-10-23, Twilio's A2P checker runs no JavaScript).
 *
 * Loads the app's own components through Vite's SSR loader (same config, aliases and env as the build), renders
 * each page body to static markup, checks the required text is there (fails the build if not), and writes
 * scripts/generated/static-pages.js, which api/share.ts imports and places inside #root for those routes.
 * Gitignored like og-shell.js (scripts/generated/). Wired into `npm run build`.
 *
 *   node scripts/prerender-static-pages.mjs            # write the module
 *   node scripts/prerender-static-pages.mjs --print    # also print each page's size and first line of text
 */
import { mkdir, writeFile, rename } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createServer } from "vite";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outPath = path.join(root, "scripts", "generated", "static-pages.js");

// A minimal config, not vite.config.ts: that file aliases react/react-dom to absolute file paths (one React for the
// browser bundle), which makes Vite's SSR loader inline React's CommonJS as ESM and fail. Here React stays a plain
// external dependency of Node. The "@" alias, the JSX runtime and the build-time defines match the app's.
// React Router's <Link> warns about useLayoutEffect once per link on a server render, and the Supabase client
// warns that a dev server points at prod. Both are harmless here (static markup, no queries run) and are left in
// the log: a console wrapper that forwards arbitrary arguments is a clear-text-logging sink (CodeQL).
const server = await createServer({
  root,
  mode: "production",
  configFile: false,
  resolve: { alias: [{ find: "@", replacement: path.join(root, "src") }] },
  esbuild: { jsx: "automatic" },
  define: { __APP_COMMIT__: JSON.stringify("prerender"), __APP_BUILT_AT__: JSON.stringify(""), __APP_COMMIT_FULL__: JSON.stringify("prerender") },
  logLevel: "error",
  appType: "custom",
  server: { middlewareMode: true, hmr: false, watch: null },
  optimizeDeps: { noDiscovery: true, include: [] },
});
let pages;
let gaps;
try {
  const mod = await server.ssrLoadModule("/src/prerender/staticPages.tsx");
  pages = mod.renderStaticPages();
  gaps = mod.staticPageGaps(pages);
} finally {
  await server.close();
}
if (gaps.length) {
  console.error(`prerender-static-pages: the raw HTML would be missing required text:\n  ${gaps.join("\n  ")}`);
  process.exit(1);
}
await mkdir(path.dirname(outPath), { recursive: true });
const tmp = `${outPath}.${process.pid}.tmp`;
await writeFile(
  tmp,
  "// GENERATED by scripts/prerender-static-pages.mjs from src/prerender/staticPages.tsx. Do not edit.\n" +
    `export const STATIC_PAGE_BODIES = ${JSON.stringify(pages)};\n`,
);
await rename(tmp, outPath);
for (const [p, html] of Object.entries(pages)) {
  console.log(`prerender-static-pages: ${p} ${html.length} bytes`);
}
