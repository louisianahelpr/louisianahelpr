// The opt-out. Every commercial email in the product points here, and so does
// the "new job posted" email's List-Unsubscribe (`list=job_matches`, Q1585),
// which turns off only that email; see setJobMatchEmails below.
//
// ═════════════════════════════════════════════════════════════════════════
// THE PATH, HOP BY HOP
//
//   1. A commercial template renders <MarketingFooter unsubscribeUrl={…}>.
//      The sender built that URL with `buildUnsubscribeUrl(recipientEmail)`
//      (_shared/unsubscribe.ts): the address, base64url-encoded, plus an
//      HMAC-SHA256 signature over `unsub.v1:<address>`.
//   2. The same sender sets `List-Unsubscribe: <that URL>, <mailto:…>` and
//      `List-Unsubscribe-Post: List-Unsubscribe=One-Click`, so Gmail and
//      Apple Mail render their own native unsubscribe control.
//   3a. NATIVE CONTROL → the mail client POSTs `List-Unsubscribe=One-Click`
//       to this function. No session, no page, no confirmation step. RFC 8058
//       requires the unsubscribe to take effect on that POST alone.
//   3b. FOOTER LINK → the recipient GETs this function. A GET WRITES NOTHING
//       (Q1655): mail scanners, link previewers and corporate gateways GET
//       every URL in a message, and each such GET used to turn the member's
//       email off. It answers 303 to the web page /unsubscribe with the same
//       e/sig/list, which asks "Turn off …?" with one button. That button
//       POSTs `action=unsubscribe` here and the page shows the result and a
//       Resubscribe button (POST `action=resubscribe`). The page lives in the
//       web app because Supabase serves an edge function's HTML as
//       text/plain (measured 2026-10-17: this function's own error page came
//       back `content-type: text/plain` with `nosniff`, so a member saw raw
//       HTML source); a page POST answers JSON for that page to render.
//   4. This handler verifies the signature, resolves the address to a
//      profile, and writes the two reversible consent flags:
//          profiles.marketing_consent                -> false
//          notification_preferences.email_promotions -> false
//   5. Every commercial sender re-reads both flags before its next send:
//        • send-marketing-blast  — filters on both, FAIL-CLOSED on a read error
//        • engagement-automations (welcome drip, win-back) — same
//      So an opt-out generated by the digest stops the campaigns too. There
//      is no per-campaign opt-out, by design: the statute's opt-out is from
//      the sender's commercial mail, not from one message.
//
// ═════════════════════════════════════════════════════════════════════════
// WHAT THIS DELIBERATELY DOES NOT TOUCH: `suppressed_emails`
//
// That table is the HARD suppression list — hard bounces and spam complaints,
// written only by `resend-webhook`, append-only, permanent. It is read by the
// TRANSACTIONAL senders as well (send-notification-email fails closed on it;
// engagement-automations aborts its whole run if it cannot read it).
//
// So writing a commercial opt-out there would ALSO kill the recipient's
// payout notifications, job updates, password resets and security notices.
// That is not what "unsubscribe from these emails" asks for, and CAN-SPAM's
// opt-out right does not extend to transactional mail (§7702(17) puts
// transactional/relationship messages outside the commercial definition
// entirely). Two lists, two meanings:
//
//     suppressed_emails         hard, permanent, ALL mail   (bounce/complaint)
//     marketing_consent +       soft, reversible, COMMERCIAL only
//       email_promotions
//
// If you ever find yourself adding a `suppressed_emails` insert to this file,
// you are about to silence someone's escrow-release email. Don't.
//
// ═════════════════════════════════════════════════════════════════════════
// DEPLOYMENT
//
//   supabase/config.toml needs
//       [functions.email-unsubscribe]
//         verify_jwt = false
//   because a mail client's one-click POST carries no Supabase JWT, and a
//   recipient clicking the footer link is by definition not signed in.
//   Authenticity is the HMAC in the token, checked below.
//
//   Signing key: EMAIL_UNSUBSCRIBE_SECRET, falling back to CRON_SECRET (the
//   key `email-tracking` already signs with). With neither set this function
//   answers 503 and the footers fall back to the preferences page — loudly,
//   never silently.

import { createClient } from 'npm:@supabase/supabase-js@2'
import { corsHeadersFull as corsHeaders } from '../_shared/cors.ts'
import { getAppUrl } from '../_shared/appUrl.ts'
import { unsubscribeListFrom, unsubscribeSigningConfigured, verifyUnsubscribeToken } from '../_shared/unsubscribe.ts'
import { serve } from "../_shared/buildStamp.ts";

/**
 * PostgREST turns `*` into `%` and passes `%`/`_` straight into SQL ILIKE, so
 * an address containing an underscore (`john_doe@…` — extremely common) would
 * match the wrong row. Escape the three pattern characters before the
 * case-insensitive lookup.
 */
function escapeLikePattern(value: string): string {
  return value.replace(/[\\%_*]/g, (c) => `\\${c}`)
}

/**
 * Resolve an address to a profile.
 *
 * Exact match first — signup lowercases, so that is the overwhelming case —
 * then a case-insensitive fallback for rows written before that, or by an
 * admin typing mixed case.
 */
async function findProfile(
  // deno-lint-ignore no-explicit-any
  supabase: any,
  email: string,
): Promise<{ user_id: string } | null> {
  const exact = await supabase
    .from('profiles')
    .select('user_id')
    .eq('email', email)
    .limit(1)
    .maybeSingle()
  // The error is checked, never assumed away: a failed read here would
  // otherwise look identical to "this address has no account" and the
  // opt-out would be silently dropped.
  if (exact.error) throw new Error(`profile lookup failed: ${exact.error.message}`)
  if (exact.data) return exact.data

  const ci = await supabase
    .from('profiles')
    .select('user_id')
    .ilike('email', escapeLikePattern(email))
    .limit(1)
    .maybeSingle()
  if (ci.error) throw new Error(`profile lookup failed: ${ci.error.message}`)
  return ci.data ?? null
}

/**
 * Flip both consent flags for one user.
 *
 * `optOut = true` unsubscribes, `false` resubscribes. Returns nothing and
 * THROWS on failure — the caller must never report success for a write that
 * did not happen, which is the whole failure mode this endpoint exists to fix.
 *
 * `.select('user_id')` on the profiles UPDATE is deliberate: an UPDATE that
 * matches zero rows resolves `{ data: [], error: null }`, so without it a
 * user_id that no longer exists would report a successful opt-out.
 */
async function setCommercialConsent(
  // deno-lint-ignore no-explicit-any
  supabase: any,
  userId: string,
  optOut: boolean,
): Promise<void> {
  const { data: updated, error: profileError } = await supabase
    .from('profiles')
    .update({ marketing_consent: !optOut })
    .eq('user_id', userId)
    .select('user_id')
  if (profileError) throw new Error(`marketing_consent write failed: ${profileError.message}`)
  if (!updated || updated.length === 0) {
    throw new Error('marketing_consent write matched no profile row')
  }

  // Upsert, not update: `notification_preferences` rows are created lazily by
  // the app, so a user who never opened the notifications tab has no row and
  // a bare UPDATE would match zero rows and report success. `user_id` is
  // UNIQUE (migration 20260312023604), which is what makes onConflict work.
  const { error: prefsError } = await supabase
    .from('notification_preferences')
    .upsert({ user_id: userId, email_promotions: !optOut }, { onConflict: 'user_id' })
  if (prefsError) throw new Error(`email_promotions write failed: ${prefsError.message}`)
}

/**
 * Q1585: the job-match list. `send-notification-email` puts a one-click
 * List-Unsubscribe on the "new job posted" email (owner, 2026-10-12: every
 * member gets it unless they turn it off), signed for `list=job_matches`. That
 * link turns off exactly that email: notification_preferences.email_job_matches,
 * the switch on the Notifications screen. It never touches the commercial
 * consent flags or signup_leads, and the in-app alert (job_matches) stays on.
 *
 * Upsert for the same reason as setCommercialConsent (the row is created
 * lazily), with `.select('user_id')` so a write that landed nowhere throws.
 */
async function setJobMatchEmails(
  // deno-lint-ignore no-explicit-any
  supabase: any,
  userId: string,
  optOut: boolean,
): Promise<void> {
  const { data, error } = await supabase
    .from('notification_preferences')
    .upsert({ user_id: userId, email_job_matches: !optOut }, { onConflict: 'user_id' })
    .select('user_id')
  if (error) throw new Error(`email_job_matches write failed: ${error.message}`)
  if (!data || data.length === 0) throw new Error('email_job_matches write matched no row')
}

/** Every response forbids caching: each one is keyed on a signed token. */
function text(body: string, status: number): Response {
  return new Response(body, {
    status,
    headers: { ...corsHeaders, 'Content-Type': 'text/plain; charset=utf-8', 'Cache-Control': 'no-store' },
  })
}

type PageResult =
  | { status: 'unsubscribed' | 'resubscribed'; list: string }
  | { error: 'invalid_link' | 'unavailable' | 'failed' }

/** The /unsubscribe web page's answer: JSON it renders as words. */
function json(body: PageResult, status: number): Response {
  return new Response(JSON.stringify(body), {
    status,
    headers: { ...corsHeaders, 'Content-Type': 'application/json', 'Cache-Control': 'no-store' },
  })
}

/**
 * Q1655: the footer link's GET. No token check, no read, no write: it only
 * carries the signed parameters to the web page, which asks before anything
 * changes. The POST from that page is verified exactly like a one-click POST.
 */
function toConfirmPage(url: URL): Response {
  const q = new URLSearchParams()
  for (const k of ['e', 'sig', 'list']) {
    const v = url.searchParams.get(k)
    if (v !== null) q.set(k, v)
  }
  return new Response(null, {
    status: 303,
    headers: {
      ...corsHeaders,
      Location: `${getAppUrl()}/unsubscribe?${q.toString()}`,
      'Cache-Control': 'no-store',
      'X-Robots-Tag': 'noindex, nofollow',
    },
  })
}

serve(async (req) => {
  if (req.method === 'OPTIONS') return new Response(null, { headers: corsHeaders })
  if (req.method !== 'GET' && req.method !== 'POST') {
    return text('Method not allowed', 405)
  }

  const url = new URL(req.url)

  // A GET never writes (Q1655). It goes to the web page that asks first.
  if (req.method === 'GET') return toConfirmPage(url)

  // Two kinds of POST, told apart by the body:
  //   `action=unsubscribe` / `action=resubscribe`  the /unsubscribe page's
  //       buttons: answered with JSON for the page to show. The page sends
  //       the signed e/sig/list in the BODY, never the query, so the link (a
  //       credential) is not in any URL its analytics or error reporting
  //       record (lh-authz-rls review of Q1655, finding 1).
  //   anything else, `List-Unsubscribe=One-Click` included: an RFC 8058
  //       one-click unsubscribe from a mail client, answered with text, the
  //       signed parameters read from the query as before.
  let action: 'unsubscribe' | 'resubscribe' = 'unsubscribe'
  let fromPage = false
  let token = url.searchParams
  try {
    const form = new URLSearchParams(await req.text())
    const sent = form.get('action')
    if (sent === 'unsubscribe' || sent === 'resubscribe') {
      action = sent
      fromPage = true
      token = form
    }
  } catch {
    // An unreadable body is still a valid one-click unsubscribe.
  }
  const fail = (kind: 'invalid_link' | 'unavailable' | 'failed', status: number, oneClickText: string) =>
    fromPage ? json({ error: kind }, status) : text(oneClickText, status)

  if (!unsubscribeSigningConfigured()) {
    // 503, not a friendly "you're unsubscribed": telling someone their opt-out
    // worked when nothing was written is the exact defect this replaces.
    console.error('[email-unsubscribe] no EMAIL_UNSUBSCRIBE_SECRET or CRON_SECRET configured')
    return fail('unavailable', 503, 'Unsubscribe temporarily unavailable')
  }

  // The list is part of what was signed: a promotions link verifies only as
  // promotions, a job-match link only as job matches.
  const list = unsubscribeListFrom(token.get('list'))
  const email = await verifyUnsubscribeToken(token.get('e'), token.get('sig'), list)
  if (!email) return fail('invalid_link', 400, 'Invalid or expired unsubscribe link')

  const supabase = createClient(
    Deno.env.get('SUPABASE_URL')!,
    (Deno.env.get('SECRET_KEY') ?? Deno.env.get('SUPABASE_SERVICE_ROLE_KEY'))!,
  )

  let profile: { user_id: string } | null
  try {
    profile = await findProfile(supabase, email)
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err)
    console.error('[email-unsubscribe]', message)
    return fail('failed', 500, 'Unsubscribe failed, please retry')
  }

  if (!profile) {
    // No account for this address. Every commercial segment in the product
    // except the sign-up lead reminder (stamped below) is built by querying
    // `profiles`, so there is no profile flag to write. Reported as success rather than "unknown
    // address" so this endpoint cannot be used to test whether an address has
    // a Helpr account.
    //
    // Note this is the one gap: an address that is NOT a Helpr account can
    // only ever have received a `test_email` preview from the blast tool,
    // which an admin addresses by hand. It is deliberately not written to
    // `suppressed_emails` — that list is permanent and would block the
    // verification email if this person later signed up.
    console.warn('[email-unsubscribe] no profile for a validly signed address; only signup_leads is stamped')
  } else {
    try {
      if (list === 'job_matches') {
        await setJobMatchEmails(supabase, profile.user_id, action !== 'resubscribe')
      } else {
        await setCommercialConsent(supabase, profile.user_id, action !== 'resubscribe')
      }
    } catch (err) {
      const message = err instanceof Error ? err.message : String(err)
      console.error('[email-unsubscribe]', message)
      return fail('failed', 500, 'Unsubscribe failed, please retry')
    }
  }

  // Sign-up leads (owner 2026-10-09): the "Finish signing up" reminder is
  // mailed to an address with no profile, so its opt-out lands here too.
  // Zero rows is legitimate (most addresses are not leads). A failed write
  // fails the request ONLY when no profile was written above: for a member
  // the opt-out that matters already committed, so it is logged, not undone
  // into an error. A missing table (the function deployed before its
  // migration) means no reminder can exist yet, so it is nothing to write.
  // A job-match link is never a lead's: leads get no job emails.
  const { error: leadError } = list === 'job_matches' ? { error: null } : await supabase
    .from('signup_leads')
    .update({ unsubscribed_at: action === 'resubscribe' ? null : new Date().toISOString() })
    .eq('email', email)
    .select('id')
  if (leadError && leadError.code !== '42P01' && leadError.code !== 'PGRST205') {
    console.error('[email-unsubscribe] signup_leads write failed:', leadError.message)
    if (!profile) {
      return fail('failed', 500, 'Unsubscribe failed, please retry')
    }
  }

  console.log(`[email-unsubscribe] ${action} recorded`, { list, hasProfile: !!profile, fromPage })

  if (fromPage) return json({ status: action === 'resubscribe' ? 'resubscribed' : 'unsubscribed', list }, 200)
  // RFC 8058: the one-click POST answers 200 with no body the client shows.
  return text(action === 'resubscribe' ? 'Resubscribed' : 'Unsubscribed', 200)
})
