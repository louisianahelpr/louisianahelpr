#!/usr/bin/env node
/**
 * Branded /go/ short links (owner 11-18). Edits src/content/goLinks.json ({slug: {url, label}}) and rewrites its
 * server mirror src/content/goLinks.mjs, which api/go.ts reads (src/test/goLinks.test.ts fails when they differ).
 *
 *   node scripts/go-links.mjs add <slug> <url> [label]   validate and add one link
 *   node scripts/go-links.mjs --from-picks [--dry-run]   a slug for every non-Amazon affiliate gift-guide pick
 *   node scripts/go-links.mjs sync                       rewrite goLinks.mjs from goLinks.json
 *
 * Every url must be https on an allowed host (src/lib/goLinks.mjs GO_LINK_HOSTS) and NEVER Amazon: the Amazon
 * Associates agreement does not allow cloaking an Associate link behind our own domain. A slug is
 * [a-z0-9]+(-[a-z0-9]+)*, at most 64 characters. An existing slug is never repointed silently: `add` refuses a
 * slug that already maps to a different url, and --from-picks keeps every slug already in the map.
 *
 * --from-picks reads src/content/giftGuidePicks/*.json (phase 2: the UI is not wired to /go/ yet). Slug =
 * brand + product name, deduped with -2, -3...; one slug per distinct url.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { AMAZON_HOST_RE, GO_SLUG_MAX, isAllowedGoTarget, isGoSlug, slugify } from "../src/lib/goLinks.mjs";

/** Paths resolved only when run as a script (a test imports the pure helpers in a jsdom realm). */
const here = (rel) => fileURLToPath(new URL(rel, import.meta.url));
const JSON_PATH = () => here("../src/content/goLinks.json");
const MJS_PATH = () => here("../src/content/goLinks.mjs");
const PICKS_DIR = () => here("../src/content/giftGuidePicks/");

/** Map text, slugs sorted, one link per line. */
export function mapJson(map) {
  const keys = Object.keys(map).sort();
  const lines = keys.map((k, i) => `  ${JSON.stringify(k)}: ${JSON.stringify(map[k])}${i < keys.length - 1 ? "," : ""}`);
  return `{\n${lines.join("\n")}\n}\n`;
}

/** The server mirror: the same map as a plain ES module (an api function imports it like api/share.ts's .mjs files). */
export function mapModule(map) {
  const sorted = Object.fromEntries(Object.keys(map).sort().map((k) => [k, map[k]]));
  return `/** GENERATED by scripts/go-links.mjs from src/content/goLinks.json (the /go/ short links api/go.ts serves). Do not edit. */\nexport const GO_LINKS = ${JSON.stringify(sorted)};\n`;
}

/** Why `slug` -> `url` cannot be added, or null. */
export function refusal(slug, url, map = {}) {
  if (!isGoSlug(slug)) return `slug "${slug}" must be lowercase letters, digits and single hyphens (at most ${GO_SLUG_MAX})`;
  let host = "";
  try {
    host = new URL(url).hostname.toLowerCase();
  } catch {
    return `"${url}" is not a URL`;
  }
  if (AMAZON_HOST_RE.test(host)) return `Amazon links never go through /go/ (Associates agreement: no cloaking): ${host}`;
  if (!isAllowedGoTarget(url)) return `${host} is not an allowed /go/ host (src/lib/goLinks.mjs GO_LINK_HOSTS; https only)`;
  if (Object.prototype.hasOwnProperty.call(map, slug) && map[slug].url !== url) return `slug "${slug}" already points at ${map[slug].url}`;
  return null;
}

/** Every allowed, non-Amazon pick url not yet in `map`, given a fresh deduped brand-product slug. */
export function slugsFromPicks(picks, map) {
  const out = { ...map };
  const taken = new Set(Object.keys(out));
  const known = new Set(Object.values(out).map((v) => v.url));
  let added = 0;
  for (const p of picks) {
    const url = p?.href;
    if (typeof url !== "string" || known.has(url) || !isAllowedGoTarget(url)) continue;
    const base = slugify([p.brand, p.name].filter(Boolean).join(" ")) || "pick";
    let slug = base;
    for (let n = 2; taken.has(slug); n++) slug = `${base}-${n}`;
    const label = [p.brand, p.name].filter(Boolean).join(" ").slice(0, 120);
    out[slug] = label ? { url, label } : { url };
    taken.add(slug);
    known.add(url);
    added++;
  }
  return { map: out, added };
}

function readPicks() {
  const picks = [];
  for (const f of readdirSync(PICKS_DIR()).filter((n) => n.endsWith(".json")).sort()) {
    const chunk = JSON.parse(readFileSync(PICKS_DIR() + f, "utf8"));
    picks.push(...(chunk.picks ?? []));
  }
  return picks;
}

function save(map) {
  writeFileSync(JSON_PATH(), mapJson(map));
  writeFileSync(MJS_PATH(), mapModule(map));
}

function main(argv) {
  const map = JSON.parse(readFileSync(JSON_PATH(), "utf8"));
  const [cmd, ...rest] = argv;
  if (cmd === "add") {
    const [slug, url, ...label] = rest;
    const why = refusal(slug, url, map);
    if (why) {
      console.error(`go-links: refused: ${why}`);
      return 1;
    }
    map[slug] = label.length ? { url, label: label.join(" ") } : { url };
    save(map);
    console.log(`go-links: /go/${slug} -> ${url}`);
    return 0;
  }
  if (cmd === "--from-picks") {
    const { map: next, added } = slugsFromPicks(readPicks(), map);
    if (!rest.includes("--dry-run")) save(next);
    console.log(`go-links: ${added} pick link(s) ${rest.includes("--dry-run") ? "would be " : ""}added (${Object.keys(next).length} in the map)`);
    return 0;
  }
  if (cmd === "sync") {
    for (const [slug, v] of Object.entries(map)) {
      const why = refusal(slug, v?.url);
      if (why) {
        console.error(`go-links: refused: ${why}`);
        return 1;
      }
    }
    save(map);
    return 0;
  }
  console.error("usage: node scripts/go-links.mjs add <slug> <url> [label] | --from-picks [--dry-run] | sync");
  return 2;
}

if (import.meta.url.startsWith("file:") && process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) process.exitCode = main(process.argv.slice(2));
