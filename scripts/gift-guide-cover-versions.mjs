#!/usr/bin/env node
/**
 * COVER CACHE KEYS (owner 2026-11-21: "the colors on the cover need to match the color when you click into the guide").
 * The covers (public/gift-guides/covers/<slug>.webp) and share images (public/gift-guides/og/<slug>.jpg) keep one URL
 * while their art changes, so browsers and the service worker's static-images cache kept showing the old colours. This
 * writes src/lib/giftGuideCoverVersions.mjs: each file's first 8 hex of its MD5. src/content/giftGuideCatalog.ts and
 * api/share.ts add `?v=<hash>`, so a redrawn cover is a new URL. scripts/gift-guide-photo-covers.py runs this after
 * every redraw.
 *   node scripts/gift-guide-cover-versions.mjs           rewrite the file
 *   node scripts/gift-guide-cover-versions.mjs --check   exit 1 when the file is stale
 * Guard: src/test/giftGuideCoverVersions1121.test.ts.
 */
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const VERSIONS_FILE = join(ROOT, "src", "lib", "giftGuideCoverVersions.mjs");

/** { name: first 8 hex of MD5 } for every `ext` file in `dir`, by name. */
export function hashes(dir, ext) {
  const out = {};
  for (const f of readdirSync(dir).filter((x) => x.endsWith(ext)).sort()) {
    out[f.slice(0, -ext.length)] = createHash("md5").update(readFileSync(join(dir, f))).digest("hex").slice(0, 8);
  }
  return out;
}

/** The generated module's text. */
export function versionsSource(root = ROOT) {
  const covers = hashes(join(root, "public", "gift-guides", "covers"), ".webp");
  const og = hashes(join(root, "public", "gift-guides", "og"), ".jpg");
  return (
    "/** GENERATED by scripts/gift-guide-cover-versions.mjs: first 8 hex of each file's MD5, the ?v= cache key. Do not edit. */\n" +
    `export const COVER_VERSIONS = ${JSON.stringify(covers)};\n` +
    `export const OG_VERSIONS = ${JSON.stringify(og)};\n`
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = versionsSource();
  if (process.argv.includes("--check")) {
    let current = null;
    try {
      current = readFileSync(VERSIONS_FILE, "utf8");
    } catch (e) {
      if (e?.code !== "ENOENT") throw e; // a missing file is simply stale
    }
    const ok = current === text;
    console.log(ok ? "gift-guide-cover-versions: current" : "gift-guide-cover-versions: STALE (run node scripts/gift-guide-cover-versions.mjs)");
    process.exit(ok ? 0 : 1);
  }
  writeFileSync(VERSIONS_FILE, text);
  console.log(`gift-guide-cover-versions: wrote ${VERSIONS_FILE.slice(ROOT.length + 1)}`);
}
