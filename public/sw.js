/*
 * Minimal app-shell service worker for offline boot.
 *
 * Two distinct service workers exist in this repo:
 *
 *   1. THIS FILE — `public/sw.js` — copied verbatim into `dist/` by Vite.
 *      Ships in the Capacitor (iOS/Android) bundle, where vite-plugin-pwa
 *      is DISABLED (see vite.config.ts: the VitePWA() plugin is gated by
 *      `!isCapacitorBuild`). In that build the app is loaded from
 *      `file://` so a SW is largely moot, but if the host shell ever
 *      decides to serve from a https origin (or run in a webview that
 *      keeps a SW registration), this minimal SW gives us an offline-
 *      capable shell with network-first HTML + cache-first assets.
 *
 *   2. The Workbox SW generated by vite-plugin-pwa — for production WEB
 *      builds only. It OVERWRITES this file in dist/, so on web users
 *      get the richer Workbox runtime with HTML NetworkFirst (3s
 *      timeout), Supabase API NetworkFirst, and hashed-asset SWR. See
 *      `vite.config.ts` -> `VitePWA({ workbox: {...} })` for the full
 *      ruleset. The web Workbox SW is a strict superset of what this
 *      file does, so registering `/sw.js` works on both builds — the
 *      browser only ever sees one of them depending on origin.
 *
 * Strategy here (kept deliberately minimal, no Workbox runtime):
 *
 *   • Document requests (HTML) → NetworkFirst. Falls through to the
 *     last cached index.html when offline so the SPA still boots. A
 *     successful fetch refreshes the cache so a new deploy is picked
 *     up on the next reload.
 *
 *   • Same-origin hashed bundle assets (/assets/*.{js,css,woff2,
 *     webp,png,svg,...}) → CacheFirst. Filenames are content-hashed
 *     so a stale entry can never lie about the current code — a new
 *     deploy ships new URLs, and the cache only grows.
 *
 *   • Everything else → pass through to network (no caching).
 *
 *   • skipWaiting() + clients.claim() so a new SW takes over without a
 *     second full reload — matches the web Workbox SW's behavior.
 *
 * Registration: `src/main.tsx` registers `/sw.js` in production. On the
 * web build vite-plugin-pwa ALSO auto-injects a deferred registerSW.js
 * via `injectRegister: "script-defer"`, but `register()` is idempotent
 * so the double-register is a no-op — both calls resolve to the same
 * underlying registration.
 */

// Bump this when the strategy changes so old SWs trigger an update tick.
const CACHE_VERSION = 'v1';
const SHELL_CACHE = `helpr-shell-${CACHE_VERSION}`;
const ASSET_CACHE = `helpr-assets-${CACHE_VERSION}`;

// The single page that backs every SPA navigation. Cached on install so
// a cold offline boot still hydrates the React tree.
const APP_SHELL = ['/', '/index.html'];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(SHELL_CACHE)
      .then((cache) =>
        // `addAll` rejects atomically if any request fails. `add()` per
        // entry is more forgiving for partially-deployed builds.
        Promise.all(
          APP_SHELL.map((url) =>
            cache.add(new Request(url, { cache: 'reload' })).catch(() => null),
          ),
        ),
      )
      // Take over without waiting for tabs to close — matches the
      // Workbox SW's `skipWaiting: true`.
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      // Evict any previous-version caches (helpr-shell-v0 etc.) so an
      // updated SW doesn't accumulate stale shells indefinitely.
      const keys = await caches.keys();
      await Promise.all(
        keys
          .filter((k) => k.startsWith('helpr-') && k !== SHELL_CACHE && k !== ASSET_CACHE)
          .map((k) => caches.delete(k)),
      );
      // Mirror the Workbox SW's `clientsClaim: true` so existing tabs
      // start using the new SW immediately rather than after a second
      // reload.
      await self.clients.claim();
    })(),
  );
});

// Hashed bundle assets emitted by Vite — filename ends with the
// content hash before the extension, so a same-URL match always
// refers to the same bytes. Safe to CacheFirst aggressively.
function isHashedAsset(url) {
  return (
    url.pathname.startsWith('/assets/') &&
    /\.(js|css|woff2?|webp|png|jpg|jpeg|svg|gif|ico)$/.test(url.pathname)
  );
}

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;

  const url = new URL(req.url);

  // Only handle same-origin requests. Cross-origin (Supabase, Stripe,
  // analytics) is left to the browser so we don't accidentally cache
  // auth-sensitive responses.
  if (url.origin !== self.location.origin) return;

  // SPA document navigations → NetworkFirst with shell fallback. We
  // never cache the *navigation response* directly because Vite's
  // hashed asset URLs change every deploy; we always want to fall back
  // to the LATEST index.html we've seen, not a snapshot from two
  // deploys ago.
  if (req.mode === 'navigate' || req.destination === 'document') {
    event.respondWith(
      (async () => {
        try {
          const fresh = await fetch(req);
          const cache = await caches.open(SHELL_CACHE);
          // Stash a copy of `/` so the offline fallback always works
          // even for deep-link navigations.
          cache.put('/', fresh.clone()).catch(() => null);
          return fresh;
        } catch {
          const cache = await caches.open(SHELL_CACHE);
          const cached = (await cache.match('/')) || (await cache.match('/index.html'));
          if (cached) return cached;
          // Nothing cached — return a minimal offline page so the
          // browser doesn't show its default chrome-error screen.
          return new Response(
            '<!doctype html><meta charset="utf-8"><title>Offline</title>' +
              '<style>body{font-family:system-ui;padding:2rem;text-align:center}</style>' +
              '<h1>You are offline</h1><p>Reconnect to load Helpr.</p>',
            { headers: { 'content-type': 'text/html; charset=utf-8' } },
          );
        }
      })(),
    );
    return;
  }

  // Hashed assets → CacheFirst (filenames are immutable for a given
  // hash, so a cached entry is always correct).
  if (isHashedAsset(url)) {
    event.respondWith(
      (async () => {
        const cache = await caches.open(ASSET_CACHE);
        const cached = await cache.match(req);
        if (cached) return cached;
        try {
          const fresh = await fetch(req);
          if (fresh.ok) cache.put(req, fresh.clone()).catch(() => null);
          return fresh;
        } catch (err) {
          // No cached copy + offline → let the browser surface the
          // failure (which the React app can react to). Don't fabricate
          // a fake 200 — that could mask deploy issues.
          throw err;
        }
      })(),
    );
    return;
  }

  // Everything else: pass through. No caching, no offline fallback.
});
