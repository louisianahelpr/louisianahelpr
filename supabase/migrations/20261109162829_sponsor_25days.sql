-- Adds a brand and returns its ref code ("Cajun Candle Co." -> cajun-candle-co; -2, -3 ... if taken).
CREATE OR REPLACE FUNCTION public.sponsor_admin_add_invite(p_brand text, p_email text DEFAULT NULL)
RETURNS text
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_base text;
  v_code text;
  n integer := 1;
BEGIN
  IF NOT COALESCE(public.has_role((SELECT auth.uid()), 'admin'::app_role), false) THEN
    RAISE EXCEPTION 'not_authorized' USING ERRCODE = '42501';
  END IF;
  PERFORM public.sponsor_require_admin();  -- the admin check again, plus the switch
  v_base := left(btrim(regexp_replace(regexp_replace(lower(COALESCE(p_brand, '')), '&', ' and ', 'g'), '[^a-z0-9]+', '-', 'g'), '-'), 56);
  v_base := btrim(v_base, '-');
  IF v_base = '' THEN v_base := 'brand'; END IF;
  v_code := v_base;
  WHILE EXISTS (SELECT 1 FROM public.sponsor_invites WHERE ref_code = v_code) LOOP
    n := n + 1;
    v_code := v_base || '-' || n;
  END LOOP;
  INSERT INTO public.sponsor_invites (brand, email, ref_code) VALUES (btrim(p_brand), nullif(lower(btrim(COALESCE(p_email, ''))), ''), v_code);
  RETURN v_code;
END;
$function$;

