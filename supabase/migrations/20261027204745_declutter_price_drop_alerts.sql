-- DECLUTTER PRICE-DROP ALERTS FOR WATCHERS (owner 2026-10-27, Q2429): "Everyone watching an item is
-- told (bell + push + email per prefs) when its price drops or it becomes Free; one notice per drop,
-- rate-limited, never to the seller."
--
-- Before: only the evening price-drop sweep told watchers (an 'info' bell + push, no email), every
-- single day it dropped an item 5%, and a seller's own price cut or a switch to Free told nobody.
--
-- Now ONE trigger on declutter_items, AFTER UPDATE OF current_price_cents, covers every path that
-- lowers a live item's price (the sweep, the seller's edit, Free, and Q2430's auto-free):
--   - who: every watcher of the item (declutter_watchlist), never the seller, never a member the
--     seller has blocked or who blocked the seller, and a seed (test) listing alerts only seed
--     watchers (Q137, as the sweep did);
--   - how often (rate limit, declutter_price_alerts is the ledger): one notice per drop, at most one
--     per item per watcher every 3 days (the sweep drops 5% a day), and at most 5 price notices per
--     watcher a day across items; "now free" is always sent (it is the last drop);
--   - what: '"<title>" dropped to $X.' or '"<title>" is now free.', linking to the item; type
--     'new_offers' (push and email follow that preference: notification_preferences.new_offers /
--     email_new_offers); the email goes through send-notification-email as job alerts do.
--   - a failure never stops the price change: each watcher's notice is its own sub-block, the email its
--     own inner block (a failed email keeps the bell), and every failure goes to log_cron_defect;
--   - a hidden seller's listing (seller_hidden) tells nobody: its watchers cannot open it.
-- declutter_price_drop_sweep is restated from its newest definition (20261014224914) with only its
-- inline watcher notice removed (the trigger sends it now).
--
-- Replay-safe: IF NOT EXISTS / CREATE OR REPLACE / DROP TRIGGER IF EXISTS; grants by role name.
-- Proof: src/test/pglite/declutterPriceDropAlerts.pglite.mjs (3x replay). Guard:
-- src/test/declutterPriceDropAlerts.test.ts.

-- The ledger (rate limit and evidence). Service role only; deleted with the member or the item.
CREATE TABLE IF NOT EXISTS public.declutter_price_alerts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id uuid NOT NULL REFERENCES public.declutter_items(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  price_cents integer NOT NULL CHECK (price_cents >= 0),
  sent_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS declutter_price_alerts_item_user_idx ON public.declutter_price_alerts (item_id, user_id, sent_at DESC);
CREATE INDEX IF NOT EXISTS declutter_price_alerts_user_idx ON public.declutter_price_alerts (user_id, sent_at DESC);
ALTER TABLE public.declutter_price_alerts ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.declutter_price_alerts FROM PUBLIC, anon, authenticated;
GRANT ALL ON TABLE public.declutter_price_alerts TO service_role;

CREATE OR REPLACE FUNCTION public.declutter_price_drop_alert()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $fn$
DECLARE
  w record;
  v_free boolean := NEW.current_price_cents = 0;
  v_title text;
  v_message text;
  v_link text := '/declutter/item/' || NEW.id::text;
  v_notified bigint;
BEGIN
  -- A seller out of Declutter keeps 'live' rows hidden (seller_hidden): their watchers cannot open them (review #3).
  IF NEW.status <> 'live' OR NEW.seller_hidden OR NEW.current_price_cents >= OLD.current_price_cents THEN
    RETURN NEW;
  END IF;
  v_title := CASE WHEN v_free THEN 'Now free' ELSE 'Price dropped' END;
  v_message := CASE WHEN v_free THEN format('"%s" is now free.', NEW.title)
                    ELSE format('"%s" dropped to $%s.', NEW.title, to_char(NEW.current_price_cents / 100.0, 'FM999990.00')) END;
  FOR w IN
    SELECT wl.user_id
      FROM public.declutter_watchlist wl
      LEFT JOIN public.profiles wp ON wp.user_id = wl.user_id
     WHERE wl.item_id = NEW.id
       AND wl.user_id IS DISTINCT FROM NEW.seller_id
       -- Q137: a seed (test) listing never alerts a real watcher.
       AND (NOT NEW.is_seed OR COALESCE(wp.is_seed, false))
       AND NOT public.are_users_blocked(wl.user_id, NEW.seller_id)
       -- One per item per watcher every 3 days ("now free" always goes: it is the last drop).
       AND (v_free OR NOT EXISTS (SELECT 1 FROM public.declutter_price_alerts a
                                   WHERE a.item_id = NEW.id AND a.user_id = wl.user_id AND a.sent_at > now() - interval '3 days'))
       -- At most 5 price notices per watcher a day, across items.
       AND (SELECT count(*) FROM public.declutter_price_alerts a
             WHERE a.user_id = wl.user_id AND a.sent_at > now() - interval '1 day') < 5
  LOOP
    BEGIN
      v_notified := NULL;
      INSERT INTO public.notifications (user_id, type, title, message, link)
      VALUES (w.user_id, 'new_offers', v_title, v_message, v_link)
      RETURNING id INTO v_notified;
      -- The seed boundary trigger can suppress the bell: then nothing was told, nothing is counted, no email (review #4).
      IF v_notified IS NOT NULL THEN
        INSERT INTO public.declutter_price_alerts (item_id, user_id, price_cents) VALUES (NEW.id, w.user_id, NEW.current_price_cents);
        -- The email in its own block: a failed email never takes the bell and the ledger with it (review #1).
        BEGIN
          IF to_regnamespace('net') IS NOT NULL THEN
            PERFORM net.http_post(
              url := (SELECT decrypted_secret FROM vault.decrypted_secrets WHERE name = 'supabase_url' LIMIT 1) || '/functions/v1/send-notification-email',
              headers := jsonb_build_object(
                'Content-Type', 'application/json',
                'Authorization', 'Bearer ' || (SELECT decrypted_secret FROM vault.decrypted_secrets WHERE name = 'service_role_key' LIMIT 1)),
              body := jsonb_build_object('user_id', w.user_id, 'title', v_title, 'message', v_message, 'type', 'new_offers', 'link', v_link));
          END IF;
        EXCEPTION WHEN OTHERS THEN
          RAISE WARNING 'declutter_price_drop_alert: item % watcher % email not queued: %', NEW.id, w.user_id, SQLERRM;
          PERFORM public.log_cron_defect('declutter_price_drop_alert', NEW.id::text, SQLERRM,
            jsonb_build_object('watcher', w.user_id, 'step', 'email'));
        END;
      END IF;
    EXCEPTION WHEN OTHERS THEN
      -- A price change never fails because a watcher could not be told; the defect is logged where ops sees it (review #2).
      RAISE WARNING 'declutter_price_drop_alert: item % watcher % not told: %', NEW.id, w.user_id, SQLERRM;
      PERFORM public.log_cron_defect('declutter_price_drop_alert', NEW.id::text, SQLERRM,
        jsonb_build_object('watcher', w.user_id, 'step', 'notice'));
    END;
  END LOOP;
  RETURN NEW;
END;
$fn$;
REVOKE ALL ON FUNCTION public.declutter_price_drop_alert() FROM PUBLIC, anon, authenticated;
DROP TRIGGER IF EXISTS trg_declutter_items_price_drop_alert ON public.declutter_items;
CREATE TRIGGER trg_declutter_items_price_drop_alert AFTER UPDATE OF current_price_cents ON public.declutter_items
  FOR EACH ROW WHEN (NEW.current_price_cents < OLD.current_price_cents)
  EXECUTE FUNCTION public.declutter_price_drop_alert();

-- The evening sweep, restated from 20261014224914 without its inline watcher notice.
CREATE OR REPLACE FUNCTION public.declutter_price_drop_sweep()
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $fn$
DECLARE
  v_today date := (now() AT TIME ZONE 'America/Chicago')::date;
  v_n integer := 0;
  r record;
BEGIN
  FOR r IN
    UPDATE public.declutter_items i
       -- Never below the stop point, which is always above the floor (B42).
       SET current_price_cents = greatest(p.floor_price_cents, COALESCE(p.drop_stop_cents, p.floor_price_cents),
                                          floor(i.current_price_cents * 0.95)::integer),
           last_price_drop_on = v_today,
           price_dropped_at = now(),
           updated_at = now()
      FROM public.declutter_item_private p
     WHERE p.item_id = i.id
       AND i.status = 'live'
       AND i.sale_mode = 'offers'
       AND i.live_at IS NOT NULL AND i.live_at <= now() - interval '12 hours'
       AND i.current_price_cents > greatest(p.floor_price_cents, COALESCE(p.drop_stop_cents, p.floor_price_cents))
       AND (i.last_price_drop_on IS NULL OR i.last_price_drop_on < v_today)
    RETURNING i.id, i.title, i.current_price_cents, i.is_seed
  LOOP
    -- Q2429: the watchers' "price dropped" notice is sent by trg_declutter_items_price_drop_alert
    -- (every path that lowers a price, rate-limited), no longer from here.
    v_n := v_n + 1;
  END LOOP;
  RETURN v_n;
END;
$fn$;
REVOKE ALL ON FUNCTION public.declutter_price_drop_sweep() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.declutter_price_drop_sweep() TO service_role;

