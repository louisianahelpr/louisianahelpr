-- ── Public read ────────────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.sponsor_public_state(p_ref text DEFAULT NULL)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_ref text := lower(btrim(COALESCE(p_ref, '')));
  v_settings public.sponsor_settings;
BEGIN
  IF NOT public.sponsor_25days_on_for((SELECT auth.uid())) THEN
    RETURN jsonb_build_object('on', false);
  END IF;
  SELECT * INTO v_settings FROM public.sponsor_settings WHERE id;
  RETURN jsonb_build_object(
    'on', true,
    'greeting_brand', (SELECT i.brand FROM public.sponsor_invites i WHERE v_ref <> '' AND i.ref_code = v_ref),
    'day_counts', COALESCE((SELECT jsonb_object_agg(d.day::text, d.n)
                              FROM (SELECT day, count(*)::int AS n FROM public.sponsor_days GROUP BY day) d), '{}'::jsonb),
    'max_per_day', v_settings.max_per_day,
    'wall', COALESCE((SELECT jsonb_agg(jsonb_build_object('id', s.id, 'brand', s.brand_name, 'website', s.website,
                                                          'hasLogo', s.logo_path IS NOT NULL) ORDER BY s.created_at)
                        FROM public.sponsor_signups s
                       WHERE s.status IN ('confirmed', 'prize_received', 'posted') AND s.show_on_wall AND s.wall_ok), '[]'::jsonb),
    'testimonials', COALESCE((SELECT jsonb_agg(jsonb_build_object('id', t.id, 'quote', t.quote, 'name', t.name, 'brand', t.brand)
                                               ORDER BY t.created_at)
                                FROM public.sponsor_testimonials t WHERE t.approved), '[]'::jsonb),
    'stats', jsonb_build_object('group_members', v_settings.group_members, 'page_followers', v_settings.page_followers,
                                'monthly_visitors', v_settings.monthly_visitors),
    'has_founder_photo', v_settings.founder_photo_path IS NOT NULL
  );
END;
$function$;
REVOKE ALL ON FUNCTION public.sponsor_public_state(text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.sponsor_public_state(text) TO anon, authenticated, service_role;

-- ── Public write: one visit row (insert only) ──────────────────────────────
CREATE OR REPLACE FUNCTION public.sponsor_log_visit(p_ref text, p_referrer text, p_device text)
RETURNS void
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_ref text := lower(btrim(COALESCE(p_ref, '')));
  v_referrer text := left(btrim(COALESCE(p_referrer, '')), 200);
  v_device text := CASE WHEN p_device IN ('phone', 'tablet', 'desktop') THEN p_device ELSE 'unknown' END;
  v_headers jsonb;
  v_addr text;
  v_bucket text;
BEGIN
  IF NOT public.sponsor_25days_on_for((SELECT auth.uid())) THEN
    RAISE EXCEPTION 'feature_disabled' USING ERRCODE = '42501';
  END IF;
  IF v_ref !~ '^[a-z0-9](?:[a-z0-9-]{0,62}[a-z0-9])?$' THEN v_ref := NULL; END IF;
  IF v_referrer !~ '^https?://' THEN v_referrer := NULL; END IF;

  -- Rate limit: 20 visits per address per 10 minutes, 3000 per hour overall. The platform's address is the LAST
  -- x-forwarded-for entry (each proxy appends; earlier entries are the caller's own text). Only a hash of it
  -- with the date is kept, in sponsor_visit_hits, for a day.
  BEGIN
    v_headers := nullif(current_setting('request.headers', true), '')::jsonb;
  EXCEPTION WHEN others THEN
    v_headers := NULL;
  END;
  v_addr := nullif(btrim(reverse(split_part(reverse(COALESCE(v_headers->>'x-forwarded-for', '')), ',', 1))), '');
  v_bucket := md5('sponsor-visit:' || COALESCE(v_addr, 'no-address') || ':' || current_date::text);
  DELETE FROM public.sponsor_visit_hits WHERE hit_at < now() - interval '1 day';
  IF (SELECT count(*) FROM public.sponsor_visit_hits WHERE bucket = v_bucket AND hit_at > now() - interval '10 minutes') >= 20
     OR (SELECT count(*) FROM public.sponsor_visit_hits WHERE hit_at > now() - interval '1 hour') >= 3000 THEN
    RETURN;  -- over the limit: the visit is not recorded (the page never depends on it)
  END IF;
  INSERT INTO public.sponsor_visit_hits (bucket) VALUES (v_bucket);
  INSERT INTO public.sponsor_visits (ref_code, referrer, device) VALUES (v_ref, v_referrer, v_device);
END;
$function$;
REVOKE ALL ON FUNCTION public.sponsor_log_visit(text, text, text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.sponsor_log_visit(text, text, text) TO anon, authenticated, service_role;

-- ── The sign-up (service role only: the sponsor-25days function, after validating) ──
CREATE OR REPLACE FUNCTION public.sponsor_create_signup(p_user_id uuid, p_signup jsonb)
RETURNS jsonb
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_id uuid := COALESCE((p_signup->>'id')::uuid, gen_random_uuid());
  v_days smallint[];
  v_any boolean := COALESCE((p_signup->>'any_day')::boolean, false);
  v_max integer;
  v_full smallint[];
BEGIN
  IF NOT public.sponsor_25days_on_for(p_user_id) THEN
    RAISE EXCEPTION 'feature_disabled' USING ERRCODE = '42501';
  END IF;
  SELECT COALESCE(array_agg(DISTINCT d::smallint ORDER BY d::smallint), '{}')
    INTO v_days
    FROM jsonb_array_elements_text(COALESCE(p_signup->'days', '[]'::jsonb)) AS d;
  IF EXISTS (SELECT 1 FROM unnest(v_days) d WHERE d NOT BETWEEN 1 AND 25) THEN
    RAISE EXCEPTION 'invalid_day' USING ERRCODE = '22023';
  END IF;
  IF cardinality(v_days) = 0 AND NOT v_any THEN
    RAISE EXCEPTION 'no_day' USING ERRCODE = '22023';
  END IF;
  IF cardinality(v_days) > 0 THEN v_any := false; END IF;

  -- The cap: one sign-up at a time decides it (transaction-scoped lock), so two brands racing for the last
  -- spot on a day cannot both get it.
  PERFORM pg_advisory_xact_lock(hashtext('sponsor_25days_days'));
  SELECT max_per_day INTO v_max FROM public.sponsor_settings WHERE id;
  IF v_max IS NOT NULL AND cardinality(v_days) > 0 THEN
    SELECT COALESCE(array_agg(d ORDER BY d), '{}') INTO v_full
      FROM unnest(v_days) d
     WHERE (SELECT count(*) FROM public.sponsor_days sd WHERE sd.day = d) >= v_max;
    IF cardinality(v_full) > 0 THEN
      RETURN jsonb_build_object('ok', false, 'full_days', to_jsonb(v_full));
    END IF;
  END IF;

  INSERT INTO public.sponsor_signups (id, brand_name, contact_name, email, phone, website, instagram, facebook, tiktok,
                                      prize_description, prize_value, ship_to, notes, any_day, wall_ok, show_on_wall,
                                      logo_path, ref_code, source)
  VALUES (v_id, btrim(p_signup->>'brand_name'), btrim(p_signup->>'contact_name'), lower(btrim(p_signup->>'email')),
          nullif(btrim(p_signup->>'phone'), ''), nullif(btrim(p_signup->>'website'), ''),
          nullif(btrim(p_signup->>'instagram'), ''), nullif(btrim(p_signup->>'facebook'), ''),
          nullif(btrim(p_signup->>'tiktok'), ''), btrim(p_signup->>'prize_description'),
          (p_signup->>'prize_value')::integer, nullif(p_signup->>'ship_to', ''), nullif(btrim(p_signup->>'notes'), ''),
          v_any, COALESCE((p_signup->>'wall_ok')::boolean, false), COALESCE((p_signup->>'wall_ok')::boolean, false),
          nullif(p_signup->>'logo_path', ''), nullif(p_signup->>'ref_code', ''), 'form');
  INSERT INTO public.sponsor_days (signup_id, day) SELECT v_id, d FROM unnest(v_days) d;
  RETURN jsonb_build_object('ok', true, 'id', v_id, 'days', to_jsonb(v_days), 'any_day', v_any);
END;
$function$;
REVOKE ALL ON FUNCTION public.sponsor_create_signup(uuid, jsonb) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.sponsor_create_signup(uuid, jsonb) TO service_role;

