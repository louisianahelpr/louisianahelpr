-- Q210(b) (owner decision 2026-09-27): a recurring visit costing $300 or more
-- is never charged off-session. 3D Secure starts at $300 (Q202,
-- _shared/threeDSecure.ts), and an off-session charge cannot run a 3DS
-- challenge: the payer is not there to answer it. So the daily
-- charge-recurring-visits run parks such a visit here as 'pending', tells the
-- payer, and the payer pays it on-session through Stripe Checkout
-- (create-payment action=recurring_visit). The checkout.session.completed
-- webhook marks the row 'paid'; charge-recurring-visits then books the visit
-- on that PaymentIntent instead of charging again. Under $300 nothing changes.
--
-- Lifecycle (only the service role writes; the payer can read their own rows):
--   pending  -> paid      webhook, on a paid Checkout session for this row
--   pending  -> expired   cron sweep, once the visit date arrives unpaid
--   paid     -> funded    cron, when the visit's job row is created on this PI
--   paid     -> refunded  cron, when the visit cannot be booked (series ended,
--                         date arrived unbooked, insert refused)

CREATE TABLE IF NOT EXISTS public.recurring_visit_payments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  parent_job_id uuid NOT NULL REFERENCES public.jobs(id) ON DELETE CASCADE,
  visit_date date NOT NULL,
  hold_id uuid,
  -- auth user id of the series poster (jobs.customer_id). Nullable: a payer
  -- who deletes their account is anonymised, the money record is not.
  payer_id uuid,
  helper_id uuid,
  budget_cents integer NOT NULL CHECK (budget_cents > 0),
  fee_cents integer NOT NULL CHECK (fee_cents >= 0),
  tax_cents integer NOT NULL DEFAULT 0 CHECK (tax_cents >= 0),
  amount_cents integer NOT NULL CHECK (amount_cents > 0),
  fee_percent numeric NOT NULL,
  tax_calculation_id text,
  status text NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'paid', 'funded', 'expired', 'refunded')),
  stripe_session_id text,
  stripe_payment_intent_id text,
  child_job_id uuid REFERENCES public.jobs(id) ON DELETE SET NULL,
  paid_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT recurring_visit_payments_amount_adds_up
    CHECK (amount_cents = budget_cents + fee_cents + tax_cents),
  CONSTRAINT recurring_visit_payments_paid_has_intent
    CHECK (status NOT IN ('paid', 'funded', 'refunded') OR stripe_payment_intent_id IS NOT NULL)
);

-- One live payment per (series, date): a second cron run, or two overlapping
-- ones, cannot ask the payer to pay the same visit twice.
CREATE UNIQUE INDEX IF NOT EXISTS recurring_visit_payments_one_live_per_date
  ON public.recurring_visit_payments (parent_job_id, visit_date)
  WHERE status IN ('pending', 'paid');

CREATE INDEX IF NOT EXISTS recurring_visit_payments_payer_idx
  ON public.recurring_visit_payments (payer_id)
  WHERE status = 'pending';

CREATE INDEX IF NOT EXISTS recurring_visit_payments_open_by_date_idx
  ON public.recurring_visit_payments (visit_date)
  WHERE status IN ('pending', 'paid');

ALTER TABLE public.recurring_visit_payments ENABLE ROW LEVEL SECURITY;

