-- The slug of a display name (profiles.full_name): "Eli Broussard" -> "eli-b",
-- the first word and the last word's initial, as the app shows names publicly
-- ("Eli B."). Pure; never NULL; "neighbor" when the name gives fewer than 3
-- usable characters or a handle that is reserved or looks like a phone number.
CREATE OR REPLACE FUNCTION public.profile_handle_base(p_full_name text)
RETURNS text
LANGUAGE sql
IMMUTABLE
SET search_path TO 'public', 'pg_temp'
AS $function$
  SELECT CASE WHEN length(b) >= 3 AND public.profile_handle_problem(b) IS NULL THEN b ELSE 'neighbor' END
    FROM (
      SELECT left(lower(f), 24) || CASE WHEN l <> '' AND cardinality(w) > 1 THEN '-' || lower(left(l, 1)) ELSE '' END AS b
        FROM (
          SELECT w,
                 regexp_replace(coalesce(w[1], ''), '[^A-Za-z0-9]+', '', 'g') AS f,
                 regexp_replace(coalesce(w[cardinality(w)], ''), '[^A-Za-z0-9]+', '', 'g') AS l
            FROM (SELECT regexp_split_to_array(btrim(coalesce(p_full_name, '')), '\s+') AS w) a
        ) b
    ) c
$function$;

REVOKE ALL ON FUNCTION public.profile_handle_base(text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.profile_handle_base(text) TO authenticated, service_role;

-- Members never write the handle columns themselves.
CREATE OR REPLACE FUNCTION public.enforce_profile_handle_server_owned()
RETURNS trigger
LANGUAGE plpgsql
SET search_path TO 'public', 'pg_temp'
AS $function$
BEGIN
  IF (NEW.handle IS DISTINCT FROM OLD.handle OR NEW.handle_changed_at IS DISTINCT FROM OLD.handle_changed_at)
     AND coalesce(current_setting('app.profile_handle_rpc', true), '') <> '1'
     AND NOT public.is_server_context() THEN
    RAISE EXCEPTION 'handle_server_owned' USING ERRCODE = '42501',
      HINT = 'Change your profile link in Settings.';
  END IF;
  RETURN NEW;
END;
$function$;

REVOKE ALL ON FUNCTION public.enforce_profile_handle_server_owned() FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS trg_profile_handle_server_owned ON public.profiles;
CREATE TRIGGER trg_profile_handle_server_owned
  BEFORE UPDATE OF handle, handle_changed_at ON public.profiles
  FOR EACH ROW EXECUTE FUNCTION public.enforce_profile_handle_server_owned();

