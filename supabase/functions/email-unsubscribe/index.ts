// The opt-out. Every commercial email in the product points here, and so does
// the "new job posted" email's List-Unsubscribe (`list=job_matches`, Q1585),
// which turns off only that email; see setJobMatchEmails below.
//
// ═════════════════════════════════════════════════════════════════════════
// THE PATH, HOP BY HOP
//
//   1. A commercial template renders <MarketingFooter unsubscribeUrl={…}>.
//      The sender built that URL with `buildUnsubscribeUrl(recipientEmail)`
//      (_shared/unsubscribe.ts): the address, base64url-encoded, plus an
//      HMAC-SHA256 signature over `unsub.v1:<address>`.
//   2. The same sender sets `List-Unsubscribe: <that URL>, <mailto:…>` and
//      `List-Unsubscribe-Post: List-Unsubscribe=One-Click`, so Gmail and
//      Apple Mail render their own native unsubscribe control.
//   3a. NATIVE CONTROL → the mail client POSTs `List-Unsubscribe=One-Click`
//       to this function. No session, no page, no confirmation step. RFC 8058
//       requires the unsubscribe to take effect on that POST alone.
//   3b. FOOTER LINK → the recipient GETs this function. The GET writes
//       NOTHING (Q1655: a mail scanner or link preview fetches URLs too) and
//       redirects to the app's /unsubscribe page with the same signed token.
//       That page shows the address and a button that POSTs here
//       (`action=unsubscribe`), then offers "resubscribe" (`action=resubscribe`)
//       in case it was a mistake. The page lives on the app because Supabase
//       serves a function's HTML as text/plain (Q?unsub-page-raw-html).
//   4. This handler verifies the signature, resolves the address to a
//      profile, and writes the two reversible consent flags:
//          profiles.marketing_consent                -> false
//          notification_preferences.email_promotions -> false
//      The first unsubscribe through a link records what the two flags were;
//      a resubscribe restores exactly that and nothing else
//      (Q?unsub-resubscribe-consent; see setCommercialConsent).
//   5. Every commercial sender re-reads both flags before its next send:
//        • send-marketing-blast  — filters on both, FAIL-CLOSED on a read error
//        • engagement-automations (welcome drip, win-back) — same
//      So an opt-out generated by the digest stops the campaigns too. There
//      is no per-campaign opt-out, by design: the statute's opt-out is from
//      the sender's commercial mail, not from one message.
//
// ═════════════════════════════════════════════════════════════════════════
// WHAT THIS DELIBERATELY DOES NOT TOUCH: `suppressed_emails`
//
// That table is the HARD suppression list — hard bounces and spam complaints,
// written only by `resend-webhook`, append-only, permanent. It is read by the
// TRANSACTIONAL senders as well (send-notification-email fails closed on it;
// engagement-automations aborts its whole run if it cannot read it).
//
// So writing a commercial opt-out there would ALSO kill the recipient's
// payout notifications, job updates, password resets and security notices.
// That is not what "unsubscribe from these emails" asks for, and CAN-SPAM's
// opt-out right does not extend to transactional mail (§7702(17) puts
// transactional/relationship messages outside the commercial definition
// entirely). Two lists, two meanings:
//
//     suppressed_emails         hard, permanent, ALL mail   (bounce/complaint)
//     marketing_consent +       soft, reversible, COMMERCIAL only
//       email_promotions
//
// If you ever find yourself adding a `suppressed_emails` insert to this file,
// you are about to silence someone's escrow-release email. Don't.
//
// ═════════════════════════════════════════════════════════════════════════
// DEPLOYMENT
//
//   supabase/config.toml needs
//       [functions.email-unsubscribe]
//         verify_jwt = false
//   because a mail client's one-click POST carries no Supabase JWT, and a
//   recipient clicking the footer link is by definition not signed in.
//   Authenticity is the HMAC in the token, checked below.
//
//   Signing key: EMAIL_UNSUBSCRIBE_SECRET, falling back to CRON_SECRET (the
//   key `email-tracking` already signs with). With neither set this function
//   answers 503 and the footers fall back to the preferences page — loudly,
//   never silently.

import { createClient } from 'npm:@supabase/supabase-js@2'
import { corsHeadersFull as corsHeaders } from '../_shared/cors.ts'
import { getAppUrl } from '../_shared/appUrl.ts'
import { unsubscribeListFrom, unsubscribeSigningConfigured, verifyUnsubscribeToken } from '../_shared/unsubscribe.ts'
import { serve } from "../_shared/buildStamp.ts";

/**
 * PostgREST turns `*` into `%` and passes `%`/`_` straight into SQL ILIKE, so
 * an address containing an underscore (`john_doe@…` — extremely common) would
 * match the wrong row. Escape the three pattern characters before the
 * case-insensitive lookup.
 */
function escapeLikePattern(value: string): string {
  return value.replace(/[\\%_*]/g, (c) => `\\${c}`)
}

/**
 * Resolve an address to a profile.
 *
 * Exact match first — signup lowercases, so that is the overwhelming case —
 * then a case-insensitive fallback for rows written before that, or by an
 * admin typing mixed case.
 */
async function findProfile(
  // deno-lint-ignore no-explicit-any
  supabase: any,
  email: string,
): Promise<{ user_id: string } | null> {
  const exact = await supabase
    .from('profiles')
    .select('user_id')
    .eq('email', email)
    .limit(1)
    .maybeSingle()
  // The error is checked, never assumed away: a failed read here would
  // otherwise look identical to "this address has no account" and the
  // opt-out would be silently dropped.
  if (exact.error) throw new Error(`profile lookup failed: ${exact.error.message}`)
  if (exact.data) return exact.data

  const ci = await supabase
    .from('profiles')
    .select('user_id')
    .ilike('email', escapeLikePattern(email))
    .limit(1)
    .maybeSingle()
  if (ci.error) throw new Error(`profile lookup failed: ${ci.error.message}`)
  return ci.data ?? null
}

/** What a promotions unsubscribe turned off, kept so its resubscribe can undo exactly that. */
type PromotionsBefore = { marketing_consent: boolean; email_promotions: boolean }

/**
 * The upsert both directions share. Upsert, not update: `notification_preferences`
 * rows are created lazily by the app, so a user who never opened the
 * notifications tab has no row and a bare UPDATE would match zero rows and
 * report success. `user_id` is UNIQUE (migration 20260312023604), which is what
 * makes onConflict work.
 */
async function writeEmailPromotions(
  // deno-lint-ignore no-explicit-any
  supabase: any,
  userId: string,
  on: boolean,
): Promise<void> {
  const { data: prefs, error: prefsError } = await supabase
    .from('notification_preferences')
    .upsert({ user_id: userId, email_promotions: on }, { onConflict: 'user_id' })
    .select('user_id')
  if (prefsError) throw new Error(`email_promotions write failed: ${prefsError.message}`)
  if (!prefs || prefs.length === 0) throw new Error('email_promotions write matched no row')
}

/** The member's email_promotions as every sender reads it: a missing row is ON. */
async function readEmailPromotions(
  // deno-lint-ignore no-explicit-any
  supabase: any,
  userId: string,
): Promise<boolean> {
  const { data, error } = await supabase
    .from('notification_preferences')
    .select('email_promotions')
    .eq('user_id', userId)
    .maybeSingle()
  if (error) throw new Error(`email_promotions read failed: ${error.message}`)
  return data ? data.email_promotions !== false : true
}

/**
 * The promotions list, for one user. THROWS on failure — the caller must never
 * report success for a write that did not happen, which is the whole failure
 * mode this endpoint exists to fix.
 *
 * Q?unsub-resubscribe-consent (owner, 2026-10-15, pop-up: "Only undo what they
 * turned off"). Resubscribe used to write marketing_consent = true and
 * email_promotions = true whatever they had been, so anyone holding a
 * promotions link (a sign-up lead reminder carries one too; the token never
 * expires) could opt in an address that never agreed to marketing, or switch
 * on promotions a member had turned off in Settings. Now:
 *   - UNSUBSCRIBE turns both off, as before, and the FIRST one through a link
 *     records what they were in profiles.promotions_before_unsubscribe (a
 *     second one keeps the first record: the UPDATE only fills an empty one, so
 *     two racing requests cannot record the half-off state). A member with no
 *     notification_preferences row is recorded as promotions ON, because that
 *     is what every sender reads a missing row as. Recording is best effort:
 *     the opt-out itself never waits on it (an RFC 8058 one-click POST that
 *     fails is not reliably retried).
 *   - RESUBSCRIBE restores exactly that record and clears it, but only while
 *     both flags are still what the unsubscribe left (off). If the member has
 *     changed either since, in Settings or anywhere else, their later choice
 *     wins: the record is cleared and nothing else is written. No record means
 *     a link never turned anything off, so it writes NOTHING: marketing consent
 *     that was never given stays off. Every read failure fails the request.
 *
 * `.select('user_id')` on the profiles UPDATEs is deliberate: an UPDATE that
 * matches zero rows resolves `{ data: [], error: null }`, so without it a
 * user_id that no longer exists would report a successful opt-out.
 */
async function setCommercialConsent(
  // deno-lint-ignore no-explicit-any
  supabase: any,
  userId: string,
  optOut: boolean,
): Promise<void> {
  const { data: profile, error: readError } = await supabase
    .from('profiles')
    .select('marketing_consent, promotions_before_unsubscribe')
    .eq('user_id', userId)
    .maybeSingle()
  const saved = (profile?.promotions_before_unsubscribe ?? null) as PromotionsBefore | null

  if (optOut) {
    if (readError) {
      console.error('[email-unsubscribe] consent read failed; opting out without a record:', readError.message)
    } else if (profile && !saved) {
      try {
        const record: PromotionsBefore = {
          marketing_consent: profile.marketing_consent === true,
          email_promotions: await readEmailPromotions(supabase, userId),
        }
        const { error: recordError } = await supabase
          .from('profiles')
          .update({ promotions_before_unsubscribe: record })
          .eq('user_id', userId)
          .is('promotions_before_unsubscribe', null)
        if (recordError) throw new Error(recordError.message)
      } catch (err) {
        console.error('[email-unsubscribe] could not record what this unsubscribe turns off:', err instanceof Error ? err.message : String(err))
      }
    }
    const { data: updated, error: profileError } = await supabase
      .from('profiles')
      .update({ marketing_consent: false })
      .eq('user_id', userId)
      .select('user_id')
    if (profileError) throw new Error(`marketing_consent write failed: ${profileError.message}`)
    if (!updated || updated.length === 0) {
      throw new Error('marketing_consent write matched no profile row')
    }
    await writeEmailPromotions(supabase, userId, false)
    return
  }

  // Resubscribe. Any read failure, including the column not deployed yet
  // (42703/PGRST204), fails the request rather than guess.
  if (readError) throw new Error(`consent read failed: ${readError.message}`)
  if (!profile) throw new Error('consent read matched no profile row')
  if (!saved) return

  const untouched = profile.marketing_consent === false && (await readEmailPromotions(supabase, userId)) === false
  if (untouched) {
    // The list first, then consent + clearing the record: if the second write
    // fails, the record is still there and a retry finishes the undo.
    await writeEmailPromotions(supabase, userId, saved.email_promotions === true)
  }
  const { data: restored, error: restoreError } = await supabase
    .from('profiles')
    .update(untouched
      ? { marketing_consent: saved.marketing_consent === true, promotions_before_unsubscribe: null }
      : { promotions_before_unsubscribe: null })
    .eq('user_id', userId)
    .select('user_id')
  if (restoreError) throw new Error(`marketing_consent restore failed: ${restoreError.message}`)
  if (!restored || restored.length === 0) throw new Error('marketing_consent restore matched no profile row')
}

/**
 * Q1585: the job-match list. `send-notification-email` puts a one-click
 * List-Unsubscribe on the "new job posted" email (owner, 2026-10-12: every
 * member gets it unless they turn it off), signed for `list=job_matches`. That
 * link turns off exactly that email: notification_preferences.email_job_matches,
 * the switch on the Notifications screen. It never touches the commercial
 * consent flags or signup_leads, and the in-app alert (job_matches) stays on.
 *
 * Upsert for the same reason as setCommercialConsent (the row is created
 * lazily), with `.select('user_id')` so a write that landed nowhere throws.
 */
async function setJobMatchEmails(
  // deno-lint-ignore no-explicit-any
  supabase: any,
  userId: string,
  optOut: boolean,
): Promise<void> {
  const { data, error } = await supabase
    .from('notification_preferences')
    .upsert({ user_id: userId, email_job_matches: !optOut }, { onConflict: 'user_id' })
    .select('user_id')
  if (error) throw new Error(`email_job_matches write failed: ${error.message}`)
  if (!data || data.length === 0) throw new Error('email_job_matches write matched no row')
}

/**
 * Q1655 + Q?unsub-page-raw-html: where a footer-link GET is sent.
 *
 * The GET used to WRITE the opt-out and then render a confirmation page from
 * this function. Both halves were wrong:
 *   - a write on a GET means any mail scanner or link previewer that fetches
 *     the URL turns the member's email off (Q1655);
 *   - Supabase serves an edge function's text/html as `text/plain` (measured
 *     on prod 2026-10-14 with `curl -sD -`), so every page it rendered showed
 *     the member raw markup.
 * So a GET writes NOTHING and answers with a redirect to the app's
 * /unsubscribe page, carrying the same signed token. That page shows the
 * address and a button; the button POSTs back here (`action=unsubscribe`, or
 * `action=resubscribe` to undo it) and the page renders the answer.
 *
 * The token rides in the FRAGMENT, not the query: a fragment is never sent to
 * a server, so it stays out of Vercel's request logs and the page-meta
 * function's logs (lh-authz-rls review of 65889d638, #2). Only e, sig and
 * list are copied; nothing else from the request reaches the Location.
 */
function appPageUrl(url: URL): string {
  const q = new URLSearchParams()
  for (const key of ['e', 'sig', 'list']) {
    const value = url.searchParams.get(key)
    if (value !== null) q.set(key, value)
  }
  return `${getAppUrl()}/unsubscribe#${q.toString()}`
}

type Action = 'unsubscribe' | 'resubscribe' | 'check'

/**
 * The answer to a POST. The app page asks for JSON (`Accept: application/json`)
 * and renders it; a mail client's RFC 8058 one-click POST gets a short text
 * body (it only reads the status).
 */
function reply(
  wantsJson: boolean,
  status: number,
  body: { ok: boolean; error?: string; action?: Action; list?: string; email?: string },
  plain: string,
): Response {
  if (wantsJson) {
    return new Response(JSON.stringify(body), {
      status,
      headers: { ...corsHeaders, 'Content-Type': 'application/json', 'Cache-Control': 'no-store' },
    })
  }
  return new Response(plain, {
    status,
    headers: { ...corsHeaders, 'Content-Type': 'text/plain; charset=utf-8', 'Cache-Control': 'no-store' },
  })
}

serve(async (req) => {
  if (req.method === 'OPTIONS') return new Response(null, { headers: corsHeaders })
  if (req.method !== 'GET' && req.method !== 'POST') {
    return reply(false, 405, { ok: false, error: 'method' }, 'Method not allowed')
  }

  const url = new URL(req.url)

  // A GET never writes (Q1655): it hands the signed link to the app page.
  if (req.method === 'GET') {
    return new Response(null, {
      status: 302,
      headers: {
        ...corsHeaders,
        Location: appPageUrl(url),
        'Cache-Control': 'no-store',
        'X-Robots-Tag': 'noindex, nofollow',
        'Referrer-Policy': 'no-referrer',
      },
    })
  }

  const wantsJson = (req.headers.get('accept') ?? '').includes('application/json')

  // A one-click POST from a mail client carries `List-Unsubscribe=One-Click`
  // as a form body; the app page posts `action=unsubscribe`, `action=check`
  // (verify the link and say whose it is, writing nothing) or
  // `action=resubscribe`. Anything else is treated as an unsubscribe.
  let action: Action = 'unsubscribe'
  try {
    const asked = new URLSearchParams(await req.text()).get('action')
    if (asked === 'resubscribe' || asked === 'check') action = asked
  } catch {
    // An unreadable body is still a valid one-click unsubscribe.
  }

  if (!unsubscribeSigningConfigured()) {
    // 503, not a friendly "you're unsubscribed": telling someone their opt-out
    // worked when nothing was written is the exact defect this replaces.
    console.error('[email-unsubscribe] no EMAIL_UNSUBSCRIBE_SECRET or CRON_SECRET configured')
    return reply(wantsJson, 503, { ok: false, error: 'unavailable' }, 'Unsubscribe temporarily unavailable')
  }

  // The list is part of what was signed: a promotions link verifies only as
  // promotions, a job-match link only as job matches.
  const list = unsubscribeListFrom(url.searchParams.get('list'))
  const email = await verifyUnsubscribeToken(url.searchParams.get('e'), url.searchParams.get('sig'), list)
  if (!email) {
    return reply(wantsJson, 400, { ok: false, error: 'invalid_link' }, 'Invalid or expired unsubscribe link')
  }

  // The page's first call: is this link good, and for which address? Nothing
  // is written, so a script that runs the page cannot change anything either.
  if (action === 'check') {
    return reply(wantsJson, 200, { ok: true, action, list, email }, 'Valid')
  }

  const supabase = createClient(
    Deno.env.get('SUPABASE_URL')!,
    (Deno.env.get('SECRET_KEY') ?? Deno.env.get('SUPABASE_SERVICE_ROLE_KEY'))!,
  )

  let profile: { user_id: string } | null
  try {
    profile = await findProfile(supabase, email)
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err)
    console.error('[email-unsubscribe]', message)
    return reply(wantsJson, 500, { ok: false, error: 'failed' }, 'Unsubscribe failed, please retry')
  }

  if (!profile) {
    // No account for this address. Every commercial segment in the product
    // except the sign-up lead reminder (stamped below) is built by querying
    // `profiles`, so there is no profile flag to write. Reported as success rather than "unknown
    // address" so this endpoint cannot be used to test whether an address has
    // a Helpr account.
    //
    // Note this is the one gap: an address that is NOT a Helpr account can
    // only ever have received a `test_email` preview from the blast tool,
    // which an admin addresses by hand. It is deliberately not written to
    // `suppressed_emails` — that list is permanent and would block the
    // verification email if this person later signed up.
    console.warn('[email-unsubscribe] no profile for a validly signed address; only signup_leads is stamped')
  } else {
    try {
      if (list === 'job_matches') {
        await setJobMatchEmails(supabase, profile.user_id, action !== 'resubscribe')
      } else {
        await setCommercialConsent(supabase, profile.user_id, action !== 'resubscribe')
      }
    } catch (err) {
      const message = err instanceof Error ? err.message : String(err)
      console.error('[email-unsubscribe]', message)
      return reply(wantsJson, 500, { ok: false, error: 'failed' }, 'Unsubscribe failed, please retry')
    }
  }

  // Sign-up leads (owner 2026-10-09): the "Finish signing up" reminder is
  // mailed to an address with no profile, so its opt-out lands here too.
  // Zero rows is legitimate (most addresses are not leads). A failed write
  // fails the request ONLY when no profile was written above: for a member
  // the opt-out that matters already committed, so it is logged, not undone
  // into an error page. A missing table (the function deployed before its
  // migration) means no reminder can exist yet, so it is nothing to write.
  // A job-match link is never a lead's: leads get no job emails.
  const { error: leadError } = list === 'job_matches' ? { error: null } : await supabase
    .from('signup_leads')
    .update({ unsubscribed_at: action === 'resubscribe' ? null : new Date().toISOString() })
    .eq('email', email)
    .select('id')
  if (leadError && leadError.code !== '42P01' && leadError.code !== 'PGRST205') {
    console.error('[email-unsubscribe] signup_leads write failed:', leadError.message)
    if (!profile) {
      return reply(wantsJson, 500, { ok: false, error: 'failed' }, 'Unsubscribe failed, please retry')
    }
  }

  console.log(`[email-unsubscribe] ${action} recorded`, { list, hasProfile: !!profile, wantsJson })

  // RFC 8058: the one-click POST answers 200; the app page renders the JSON.
  return reply(
    wantsJson,
    200,
    { ok: true, action, list, email },
    action === 'resubscribe' ? 'Resubscribed' : 'Unsubscribed',
  )
})
