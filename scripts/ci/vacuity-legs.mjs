/**
 * Q1270 (2026-10-07): writes the locked Playwright legs of vacuity.yml, from
 * the MARKER line to the end of the file (the legs, their waiters, notify).
 *
 *   node scripts/ci/vacuity-legs.mjs          # rewrite .github/workflows/vacuity.yml
 *   node scripts/ci/vacuity-legs.mjs --check  # exit 1 if the committed file differs
 *
 * Each leg holds the shared-account lock under an hour (60-min job, 52-min
 * gate step, 34 min of new work: a run started just before the budget ends,
 * up to ~13 min measured, still finishes inside the step). It resumes from the
 * previous leg's done list (scripts/vacuity/legs.mjs) and the next leg's
 * waiter runs only while the previous leg reported work left. The last leg
 * fails on anything still left. Legs that are not needed are skipped, so a
 * push run (a handful of registrations) normally stops after leg 1.
 *
 * Guard: src/test/vacuityLegs.test.ts (the committed file is this output).
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
export const WORKFLOW = path.join(ROOT, ".github", "workflows", "vacuity.yml");
// 5 x 60 + scope and notify fits the Sunday prod-load window before db-drift
// (prodWorkflowSpacing rule 5); the weekly run proves one slice (legs.mjs sliceOf).
export const LEGS = 5;
export const BUDGET_MIN = 34;
export const GATE_STEP_MINUTES = 52;
export const LEG_MINUTES = 60;
export const MARKER = "  # ── GENERATED by scripts/ci/vacuity-legs.mjs (Q1270): edit the generator, not the lines below ──";

const legKey = (n) => (n === 1 ? "vacuity-e2e" : `vacuity-e2e-${n}`);
const waitKey = (n) => (n === 1 ? "wait-accounts" : `wait-e2e-${n}`);
export const LEG_NAME = "Playwright guards shown able to fail";
const legName = (n) => (n === 1 ? LEG_NAME : `${LEG_NAME} (leg ${n} of ${LEGS})`);

const LEG1_COMMENT = `  vacuity-e2e:
    # THE PLAYWRIGHT REGISTRATIONS, UNDER THE ACCOUNT LOCK (Q551, found by Q326).
    #
    # WHY THESE JOBS HOLD TEST-ACCOUNT CREDENTIALS.
    #
    # Until 2026-09-22 the job held none, so any push touching a guard that signs
    # in went red for a reason that had nothing to do with the guard. That is
    # what happened to e2e/prod-audit/activity-loading-reserve.spec.ts: its
    # mutation is real and kills locally (placeholder row 150px -> 220px against
    # a 151px real row, both surfaces), but in CI the spec never reached its
    # assertions - e2e/journeys/fixtures.ts found no PLAYWRIGHT_*_EMAIL/_PASSWORD,
    # fell through to its local service-role path, and died on \`no .env\`. The
    # gate scored that \`inconclusive\`, which is a hard failure by design, and the
    # red read as "this guard cannot fail" when the guard was fine.
    #
    # PASSWORDS ONLY, DELIBERATELY. prod-audit.yml additionally fetches a
    # service-role key, because the incomplete-profile and admin seed accounts
    # have no password stored anywhere. Nothing registered here needs those, so
    # these jobs take the four poster/helper secrets and stop there rather than
    # widening the blast radius of a job whose whole purpose is to run mutated
    # source. fixtures.ts prefers these over the service-role path, so that
    # path is never taken here.
    #
    # Those secrets are the shared accounts every other prod suite drives, so
    # every leg holds the one lock they all hold (Q326,
    # sharedAccountJobsHoldOneLock.test.ts), entered through its own Q743 waiter.
    # Leg 1 exists only when \`scope\` found a Playwright registration to run.
    #
    # LEGS (Q1270, 2026-10-07). The full set is 99 registrations over 76 guards;
    # vacuity 37288574126 took 77.6 min for 10 of them, so the weekly set is
    # hours and no single job under the one-hour cap
    # (sharedAccountLockJobsAreShort.test.ts) can hold it. Each leg runs whole
    # guard groups for ${BUDGET_MIN} min, hands its done list to the next leg
    # (scripts/vacuity/legs.mjs), and lets go of the lock in between
    # (wait-shared-accounts.mjs YIELDS_BETWEEN_LEGS). The last leg fails on
    # anything left. A scheduled run waits in the prod-load FIFO and every
    # later cron waits behind it, so it gets ${LEGS} legs (the Sunday window
    # before db-drift, prodWorkflowSpacing rule 5) and proves the slice of the
    # e2e set the scope job picked for this ISO week. Generated by
    # scripts/ci/vacuity-legs.mjs.
`;

function waiter(n) {
  const prev = legKey(n - 1);
  return `  ${waitKey(n)}:
    # Leg ${n}'s Q743 waiter (see wait-accounts): runs only while leg ${n - 1} left work.
    name: Wait for the shared accounts (queue, e2e leg ${n})
    needs: [scope, ${prev}]
    if: \${{ !cancelled() && needs.scope.outputs.have_e2e == 'true' && needs.${prev}.outputs.remaining != '' && needs.${prev}.outputs.remaining != '0' }}
    runs-on: ubuntu-latest
    timeout-minutes: 350 # waiter, e2e leg ${n}
    permissions:
      actions: read
      contents: read
    steps:
      - uses: actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1
        with:
          sparse-checkout: |
            .github/workflows
            scripts/e2e/wait-shared-accounts.mjs
          sparse-checkout-cone-mode: false
      - name: Wait until joining the shared-accounts lock bumps no waiting job
        run: node scripts/e2e/wait-shared-accounts.mjs
        env:
          GITHUB_TOKEN: \${{ github.token }}

`;
}

/** Full-line comments go from legs 2+ (leg 1 says why); ` # e2e leg N` tags stay. */
const stripComments = (text) =>
  text
    .split("\n")
    .filter((l) => !/^\s*#/.test(l))
    .join("\n");

function leg(n) {
  const out = `vacuity-legs/done-${n}.json`;
  const args = [`--budget-min ${BUDGET_MIN}`, `--done-out ${out}`, ...(n > 1 ? [`--done vacuity-legs/done-${n - 1}.json`] : []), ...(n === LEGS ? ["--last-leg"] : [])].join(" ");
  // Lines an @mutate targets carry this YAML/shell comment, so each is unique per leg.
  const T = ` # e2e leg ${n}`;
  const head =
    n === 1
      ? LEG1_COMMENT
      : `  ${legKey(n)}:
    # Leg ${n} of ${LEGS}: what leg ${n - 1} did not reach (see vacuity-e2e).
`;
  const fetchPrev =
    n === 1
      ? ""
      : `      - name: Fetch leg ${n - 1}'s done list
        uses: actions/download-artifact@3e5f45b2cfb9172054b4087a40e8e0b5a5461e7c # v8.0.1
        with:
          name: vacuity-e2e-done-${n - 1}
          path: vacuity-legs

`;
  const body = `    name: ${legName(n)}
    needs: [scope, ${waitKey(n)}]
    if: ${n === 1 ? "needs.scope.outputs.have_e2e == 'true'" : `\${{ !cancelled() && needs.${waitKey(n)}.result == 'success' }}`}
    runs-on: ubuntu-latest
    # actions: read for the deploy wait (it lists this commit's deploy runs).
    permissions:
      contents: read
      actions: read
    timeout-minutes: ${LEG_MINUTES}${T}
    concurrency:
      group: prod-lifecycle-shared-accounts
      cancel-in-progress: false
    outputs:
      remaining: \${{ steps.gate.outputs.remaining }}
    env:
      PLAYWRIGHT_SUPABASE_URL: \${{ vars.E2E_SUPABASE_URL }}
      PLAYWRIGHT_SUPABASE_ANON_KEY: \${{ vars.E2E_SUPABASE_ANON_KEY }}
      PLAYWRIGHT_POSTER_EMAIL: \${{ secrets.PLAYWRIGHT_POSTER_EMAIL }}
      PLAYWRIGHT_POSTER_PASSWORD: \${{ secrets.PLAYWRIGHT_POSTER_PASSWORD }}
      PLAYWRIGHT_HELPER_EMAIL: \${{ secrets.PLAYWRIGHT_HELPER_EMAIL }}
      PLAYWRIGHT_HELPER_PASSWORD: \${{ secrets.PLAYWRIGHT_HELPER_PASSWORD }}

    steps:
      - name: Checkout
        # Full history: the per-push scope is a diff against origin/main, and a
        # shallow clone has no merge base to diff against.
        uses: actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1
        with:
          fetch-depth: 0

      - name: Setup Node
        uses: actions/setup-node@820762786026740c76f36085b0efc47a31fe5020 # v7.0.0
        with:
          node-version: "22"
          cache: "npm"

      - name: Install dependencies
        run: npm install --no-audit --no-fund --legacy-peer-deps

      - name: Install Playwright browsers
        # Same reason as the vacuity job's install: the harness preflight fails
        # when a browser is missing.
        run: bash scripts/ci/playwright-install.sh chromium webkit${T}

      - name: Give the build the app's public Supabase config
        # The gate rebuilds the bundle itself for Playwright guards, so it does
        # not go through .github/actions/local-preview and needs VITE_* here.
        # Both values are publishable — the same pair prod-audit.yml falls back
        # to in plain text — and no secret is written by this step.
        run: |
          set -euo pipefail
          umask 077
          {
            printf 'VITE_SUPABASE_URL=%s\\n' "\${{ vars.E2E_SUPABASE_URL || 'https://fncmgoasalhdgfwzhsqa.supabase.co' }}"
            printf 'VITE_SUPABASE_ANON_KEY=%s\\n' "\${{ vars.E2E_SUPABASE_ANON_KEY || 'sb_publishable_iYs06Xj5G6Q_ezqzrSncTw_J1EiENRP' }}"
          } > .env
          test -s .env

      - name: Give prod-backed e2e guards the service-role key
        # e2e registrations (prod-audit, a11y-prod, journeys) mint their test
        # sessions through scripts/test-signin-link.mjs, which needs
        # SUPABASE_SERVICE_ROLE_KEY in .env. Without it every such guard is
        # red BEFORE its mutation and reports INCONCLUSIVE: run 35935153284
        # (2026-09-23, nightly-red #1731) had 5 of 11 registrations
        # inconclusive with "ERROR: .env is missing VITE_SUPABASE_URL and/or
        # SUPABASE_SERVICE_ROLE_KEY". Minted the same way prod-audit.yml does.
        # Guard: src/test/vacuityWorkflowsProvideServiceRole.test.ts.
        env:
          SUPABASE_ACCESS_TOKEN: \${{ secrets.SUPABASE_ACCESS_TOKEN }}
          PROJECT_REF: \${{ vars.E2E_SUPABASE_PROJECT_REF || 'fncmgoasalhdgfwzhsqa' }}
          EVENT: \${{ github.event_name }}
        run: |
          set -euo pipefail
          if [ -n "$SUPABASE_ACCESS_TOKEN" ]; then
            SERVICE_KEY=$(npx --yes supabase@2 projects api-keys --project-ref "$PROJECT_REF" --reveal -o json \\
              | node -e 'let s="";process.stdin.on("data",d=>s+=d).on("end",()=>{const k=JSON.parse(s).find(x=>x.name==="service_role");if(!k){process.exit(3)}process.stdout.write(k.api_key)})')
            echo "::add-mask::$SERVICE_KEY"
            umask 077
            printf 'SUPABASE_SERVICE_ROLE_KEY=%s\\n' "$SERVICE_KEY" >> .env${T}
          elif [ "$EVENT" = "schedule" ] || [ "$EVENT" = "workflow_dispatch" ]; then
            echo "::error::SUPABASE_ACCESS_TOKEN missing: prod-backed e2e guards cannot mint sessions."
            exit 1
          else
            # A push run without the secret. Not a false green: an e2e
            # registration in its changed set comes back INCONCLUSIVE, which
            # the gate itself fails on.
            echo "::warning::SUPABASE_ACCESS_TOKEN missing on a $EVENT run: e2e registrations that need the service-role key will be inconclusive."
          fi

      # Q432: a push that lands a migration or an edge function starts its
      # deploys at the same moment as this job. Until they finish, the
      # prod-backed registrations test the old backend and read RED before any
      # mutation (vacuity 36215687625). Wait for this commit's db-deploy and
      # functions-deploy runs, if it has any (bounded; never fails the job).
      - name: Wait for this commit's prod deploys
        if: github.event_name == 'push'
        env:
          GITHUB_TOKEN: \${{ secrets.GITHUB_TOKEN }}
        run: node scripts/ci/wait-commit-deploys.mjs${T}

${fetchPrev}      - name: Vacuity gate (Playwright registrations, leg ${n} of ${LEGS})
        id: gate
        timeout-minutes: ${GATE_STEP_MINUTES}
        env:
          # Through env, never interpolated into the script (injection-safe).
          ONLY: \${{ inputs.only }}
          VACUITY_PUSH_BEFORE: \${{ github.event.before }}${T}
          SLICE: \${{ needs.scope.outputs.slice }}
        # The same scope as the unit job, narrowed to the registrations under
        # e2e/ (--e2e), minus what earlier legs ran (scripts/vacuity/legs.mjs).
        run: |
          mkdir -p vacuity-legs
          if [ -n "\${ONLY}" ]; then
            npm run vacuity -- --e2e --only "\${ONLY}" ${args}
          elif [ "\${{ github.event_name }}" = "schedule" ] || [ "\${{ inputs.full }}" = "true" ]; then
            npm run vacuity:all -- --e2e --slice "\${SLICE}" ${args}
          else
            npm run vacuity -- --e2e ${args}
          fi

      - name: Hand the done list to the next leg
        if: always()
        uses: actions/upload-artifact@043fb46d1a93c77aae656e7c1c64a875d1fc6a0a # v7.0.1
        with:
          name: vacuity-e2e-done-${n}
          path: ${out}
          if-no-files-found: ignore
          retention-days: 7

      - name: Remove the service-role key from the runner
        if: always()
        run: rm -f .env

`;
  return head + (n === 1 ? body : stripComments(body));
}

const NOTIFY = (needs) => `  # A RED RUN HAS TO LAND SOMEWHERE. Added 2026-09-23 after vacuity — along
  # with 13 other scheduled workflows — was found failing with nobody told.
  # The drift detector had been red for THREE CONSECUTIVE DAYS (09-20, 09-21,
  # 09-22) and the nightly DB backup had not succeeded since 09-21; both are
  # invisible unless somebody opens the Actions tab, which is exactly the
  # thing the owner said nobody does.
  #
  # \`nightly-issue-sync\` opens/updates ONE \`nightly-red\` issue for this
  # workflow and closes it on the next green run, which is what makes the
  # "Nightly reds nobody read" gate able to see it at all.
  #
  # SCHEDULE AND MANUAL RUNS ONLY. A push/PR failure is already visible on the
  # commit and the PR; filing an issue for it would make the label noisy and
  # teach people to ignore it.
  notify:
    name: Report nightly result
    needs: [${needs.join(", ")}]
    if: \${{ !cancelled() && github.ref == 'refs/heads/main' && (github.event_name == 'schedule' || github.event_name == 'workflow_dispatch') }}
    runs-on: ubuntu-latest
    timeout-minutes: 5
    permissions:
      contents: read
      issues: write
      actions: write
      checks: read
    steps:
      - uses: actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1
      - uses: ./.github/actions/nightly-issue-sync
        with:
          workflow-name: vacuity
          # vacuity-e2e does not run when no Playwright registration was in scope
          # (Q551), so leg 1 is required to succeed exactly when scope said it
          # ran; a later leg runs only while work was left, and any leg that
          # failed or was cancelled makes the run red (Q1270).
          status: \${{ needs.scope.result == 'success' && needs.vacuity.result == 'success' && (needs.scope.outputs.have_e2e != 'true' || needs.vacuity-e2e.result == 'success') && !contains(needs.*.result, 'failure') && !contains(needs.*.result, 'cancelled') && 'success' || 'failure' }}
          run-url: \${{ github.server_url }}/\${{ github.repository }}/actions/runs/\${{ github.run_id }}
          github-token: \${{ secrets.GITHUB_TOKEN }}
`;

export function render() {
  const parts = [MARKER + "\n"];
  for (let n = 1; n <= LEGS; n++) {
    if (n > 1) parts.push(waiter(n));
    parts.push(leg(n));
  }
  const needs = ["scope", "vacuity"];
  for (let n = 1; n <= LEGS; n++) needs.push(...(n > 1 ? [waitKey(n)] : []), legKey(n));
  parts.push(NOTIFY(needs));
  return parts.join("");
}

/** The workflow with everything from MARKER (or, the first time, from `  vacuity-e2e:`'s comment block) replaced. */
export function apply(src) {
  let at = src.indexOf(MARKER);
  if (at < 0) at = src.indexOf("\n  vacuity-e2e:\n") + 1;
  if (at <= 0) throw new Error("vacuity.yml: neither the marker nor the vacuity-e2e job was found");
  return src.slice(0, at) + render();
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const src = readFileSync(WORKFLOW, "utf8");
  const next = apply(src);
  if (process.argv.includes("--check")) {
    if (next !== src) {
      console.error("vacuity.yml differs from scripts/ci/vacuity-legs.mjs: run `node scripts/ci/vacuity-legs.mjs`.");
      process.exit(1);
    }
    console.log("vacuity.yml legs are current.");
  } else {
    writeFileSync(WORKFLOW, next);
    console.log(`vacuity.yml: ${LEGS} locked legs written.`);
  }
}
