-- ── The silent-cron detector's view of charge-recurring-visits ─────────────
-- A visit parked for on-session payment (awaitingPayment) is a legitimate
-- disposition of a considered series, so it counts as work done.
DO $cwe$
BEGIN
  IF to_regclass('public.cron_work_expectations') IS NULL THEN
    RAISE NOTICE 'cron_work_expectations absent: skipped';
    RETURN;
  END IF;
  INSERT INTO public.cron_work_expectations
    (jobname, candidate_key, disposition_keys, min_streak, note)
  VALUES
    ('charge-recurring-visits', 'seriesConsidered', ARRAY['funded','declined','awaitingPayment','skippedUnfilled','skippedExisting','skippedEnded','skippedBanned','skippedBlocked','skippedChargeback'], 2,
     'declined, awaitingPayment (a $300+ visit waiting for the payer to pay on-session, Q210b) and every skip (a date nobody holds, already created, an ended, banned, blocked or charged-back series) are legitimate dispositions, so they count as work done; only a series that vanished entirely is suspicious.')
  ON CONFLICT (jobname) DO UPDATE
    SET candidate_key    = EXCLUDED.candidate_key,
        disposition_keys = EXCLUDED.disposition_keys,
        min_streak       = EXCLUDED.min_streak,
        note             = EXCLUDED.note;
END
$cwe$;

