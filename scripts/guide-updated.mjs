#!/usr/bin/env node
/**
 * The "Updated" day on each guide page's Q&A (owner pop-up 2026-11-22 9:40 PM: "Q&A + updated date + byline";
 * src/lib/guideQa.mjs). Writes src/content/guideUpdated.mjs: for each Q&A page, a fingerprint of the data the page
 * shows and the day (Louisiana) that fingerprint was first seen. Re-running with unchanged data rewrites the same bytes,
 * so check-generated-current stays green; changing a page's data and regenerating moves only that page's day to today.
 * Never a hand-typed date that goes stale.
 *
 *   node scripts/guide-updated.mjs            # rewrite src/content/guideUpdated.mjs
 *   node scripts/guide-updated.mjs --check    # exit 1 if a fingerprint is stale (the data changed, the file did not)
 *
 * Guard: src/test/guideAiSearch1122.test.tsx.
 */
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = "src/content/guideUpdated.mjs";
const HEADER = "/** GENERATED by scripts/guide-updated.mjs (each guide page's Q&A \"Updated\" day and its data fingerprint). Do not edit. */\n";

const read = (rel) => readFileSync(path.join(root, rel), "utf8");

/** Each Q&A page's data, as the text its fingerprint is taken from (the page's own rows, nothing else). */
export function pageInputs() {
  const deals = JSON.parse(read("src/content/giftGuideDeals.json"));
  const day = (event) => JSON.stringify(deals.filter((d) => d.event === event));
  return {
    her: read("src/content/giftGuidePicks/her.json"),
    him: read("src/content/giftGuidePicks/him.json"),
    kids: read("src/content/giftGuidePicks/kids.json"),
    "25-days-sponsors": read("src/content/giftGuidePicks/25-days-sponsors.json"),
    "black-friday": day("black-friday"),
    "small-business-saturday": read("src/content/giftGuideSmallBiz.json"),
    "cyber-monday": day("cyber-monday"),
    holidays: read("src/content/holidayHub/lights.mjs") + read("src/content/holidayHub/events.mjs"),
  };
}

export const fingerprint = (text) => createHash("sha256").update(text).digest("hex").slice(0, 16);

const louisianaToday = () =>
  new Intl.DateTimeFormat("en-CA", { timeZone: "America/Chicago", year: "numeric", month: "2-digit", day: "2-digit" }).format(new Date());

/** The next table: a page whose fingerprint is unchanged keeps its day; a new or changed one gets `today`. */
export function nextUpdated(previous, inputs, today) {
  const out = {};
  for (const [page, text] of Object.entries(inputs)) {
    const hash = fingerprint(text);
    const old = previous?.[page];
    out[page] = old && old.hash === hash && /^\d{4}-\d{2}-\d{2}$/.test(old.day) ? { day: old.day, hash } : { day: today, hash };
  }
  return out;
}

/** The committed table, read back from the module text (no import: the script must run before the file exists). */
export function parseUpdated(text) {
  const m = /export const GUIDE_UPDATED = (\{[\s\S]*\});/.exec(text ?? "");
  return m ? JSON.parse(m[1]) : {};
}

export const moduleText = (table) => `${HEADER}export const GUIDE_UPDATED = ${JSON.stringify(table, null, 2)};\n`;

const invokedDirectly = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  const file = path.join(root, OUT);
  const current = existsSync(file) ? readFileSync(file, "utf8") : "";
  const text = moduleText(nextUpdated(parseUpdated(current), pageInputs(), louisianaToday()));
  if (process.argv.includes("--check")) {
    if (current !== text) {
      console.error(`guide-updated: ${OUT} is stale (a guide page's data changed); run node scripts/guide-updated.mjs`);
      process.exit(1);
    }
    console.log(`guide-updated: ${OUT} is current`);
  } else {
    writeFileSync(file, text);
    console.log(`guide-updated: wrote ${OUT}`);
  }
}
