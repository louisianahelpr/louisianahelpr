#!/usr/bin/env node
// Derives docs/audit/form-inventory.md from the source: every file under src/
// that renders a form control, the controls it renders, and the route(s) whose
// page transitively imports it. Re-run after adding a form:
//   node scripts/form-inventory.mjs
import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "src");
const walk = (d) => readdirSync(d).flatMap((n) => {
  const p = join(d, n);
  if (statSync(p).isDirectory()) return n === "test" || n === "__tests__" ? [] : walk(p);
  return /\.(tsx|ts)$/.test(n) && !/\.(test|spec|stories)\.tsx?$/.test(n) ? [p] : [];
});
const files = walk(SRC);
const text = new Map(files.map((f) => [f, readFileSync(f, "utf8")]));

function resolveImport(from, spec) {
  let base;
  if (spec.startsWith("@/")) base = join(SRC, spec.slice(2));
  else if (spec.startsWith(".")) base = resolve(dirname(from), spec);
  else return null;
  for (const c of [base, base + ".tsx", base + ".ts", join(base, "index.tsx"), join(base, "index.ts")]) if (text.has(c)) return c;
  return null;
}
const graph = new Map();
for (const [f, t] of text) {
  const deps = new Set();
  for (const m of t.matchAll(/(?:from\s+|import\(\s*)["']([^"']+)["']/g)) {
    const r = resolveImport(f, m[1]);
    if (r) deps.add(r);
  }
  graph.set(f, deps);
}

const KINDS = [
  ["input", /<(?:input|Input)\b[^>]*?>/gs],
  ["textarea", /<(?:textarea|Textarea)\b/g],
  ["select", /<(?:select|Select)\b/g],
  ["checkbox/switch/radio", /<(?:Checkbox|Switch|RadioGroup)\b/g],
  ["otp", /<InputOTP\b/g],
  ["date/calendar", /<(?:Calendar|DatePicker|DateTimePicker)\b|type=["'](?:date|time|datetime-local)["']/g],
  ["slider", /<Slider\b/g],
];
const TYPE_RE = /type=["']([a-z-]+)["']/;
const inventory = [];
for (const [f, t] of text) {
  if (f.includes("/components/ui/")) continue;
  const counts = {};
  const inputTypes = new Set();
  let total = 0;
  for (const [k, re] of KINDS) {
    const ms = [...t.matchAll(re)];
    if (ms.length) { counts[k] = ms.length; total += ms.length; }
    if (k === "input") for (const m of ms) { const ty = TYPE_RE.exec(m[0]); inputTypes.add(ty ? ty[1] : "text"); }
  }
  if (!total) continue;
  const hints = new Set();
  for (const m of t.matchAll(/(?:placeholder|aria-label|id|name)=["']([^"'{}]{2,40})["']/g)) hints.add(m[1]);
  const maxLen = [...t.matchAll(/maxLength=\{?["']?(\d+)/g)].map((m) => m[1]);
  inventory.push({ f, counts, inputTypes: [...inputTypes], hints: [...hints].slice(0, 8), maxLen: [...new Set(maxLen)] });
}

const appFile = join(SRC, "App.tsx");
const app = text.get(appFile);
const lazyMap = {};
for (const m of app.matchAll(/const (\w+) = lazy\w*\(\s*\(\)\s*=>\s*import\(["']([^"']+)["']\)/g)) lazyMap[m[1]] = resolveImport(appFile, m[2]);
const WRAPPERS = new Set(["PageTransition", "ProtectedRoute", "AdminRoute"]);
const routes = [];
for (const m of app.matchAll(/<Route path="([^"]+)" element=\{(.*?)\}\s*\/>/g)) {
  const comps = [...m[2].matchAll(/<(\w+)/g)].map((x) => x[1]).filter((c) => lazyMap[c] && !WRAPPERS.has(c));
  if (comps.length) routes.push({ path: m[1], page: lazyMap[comps[comps.length - 1]] });
}
// BFS distance from a start file. A file is assigned to the route(s) whose
// page reaches it in the FEWEST import hops: plain reachability is useless here
// because shared hubs (nav, contexts) make nearly every file reachable from
// nearly every page.
const reach = (start) => {
  const dist = new Map([[start, 0]]);
  const q = [start];
  while (q.length) {
    const cur = q.shift();
    for (const d of graph.get(cur) ?? []) if (!dist.has(d)) { dist.set(d, dist.get(cur) + 1); q.push(d); }
  }
  return dist;
};
const pageReach = new Map(routes.map((r) => [r.path, reach(r.page)]));
const shell = reach(appFile);

const byRoute = new Map();
for (const item of inventory) {
  const ds = routes.map((r) => [r.path, pageReach.get(r.path).get(item.f)]).filter(([, d]) => d !== undefined);
  const best = Math.min(...ds.map(([, d]) => d));
  const rs = ds.filter(([, d]) => d === best).map(([p]) => p);
  const key = rs.length ? rs.join(", ")
    : shell.has(item.f) ? "(app-wide chrome, mounted from App.tsx)"
    : "(not reached from any route page — orphaned or dynamically mounted)";
  if (!byRoute.has(key)) byRoute.set(key, []);
  byRoute.get(key).push(item);
}
const rel = (f) => relative(ROOT, f);
let md = `# Form & input inventory\n\nGenerated by \`node scripts/form-inventory.mjs\` from \`src/\` — do not hand-edit.\nA file is grouped under the route(s) whose page component reaches it in the fewest import hops (App.tsx route table + static/dynamic import graph). Components shared through app chrome therefore land under the route closest to them.\n\n**${inventory.length} files render form controls, across ${byRoute.size} route groups.** Primitives in \`src/components/ui/\` are excluded. Messy-input coverage: \`e2e/happy-path/messy-input.spec.ts\`.\n\n`;
for (const [key, items] of [...byRoute].sort((a, b) => a[0].localeCompare(b[0]))) {
  md += `## ${key}\n\n| File | Controls | input types | maxLength | hints |\n|---|---|---|---|---|\n`;
  for (const i of items.sort((a, b) => a.f.localeCompare(b.f))) {
    md += `| \`${rel(i.f)}\` | ${Object.entries(i.counts).map(([k, v]) => `${k}×${v}`).join(", ")} | ${i.inputTypes.join(", ")} | ${i.maxLen.join(", ")} | ${i.hints.join(" · ").replace(/\|/g, "\\|")} |\n`;
  }
  md += "\n";
}
mkdirSync(join(ROOT, "docs/audit"), { recursive: true });
writeFileSync(join(ROOT, "docs/audit/form-inventory.md"), md);
console.log(`${inventory.length} files, ${routes.length} routes, ${byRoute.size} groups`);
