-- 25 Days of Louisiana Giveaways (owner spec 2026-11-09): the sponsor page's data.
--
-- AUTHZ (lh-authz-rls): 6 new tables, a private bucket and 17 functions.
--   * Every table: RLS on, NO policy, every privilege revoked from PUBLIC, anon and authenticated. No browser
--     reads or writes a sponsor table; brands' names, emails and prizes are never readable by the public.
--   * The public reads ONE function, sponsor_public_state(ref): on/off, the greeting brand for a ref that
--     matches an invite (the brand NAME only, never its email), per-day COUNTS (never names), the sponsor wall
--     (only Confirmed+ AND OK to show AND shown), approved testimonials, the reach stats.
--   * The public writes through sponsor_log_visit (insert-only, rate limited, ref + referrer origin + coarse
--     device, nothing else) and the sponsor-25days edge function (service role), which validates and then
--     calls sponsor_create_signup (service role only; the per-day cap is enforced here, under a lock).
--   * sponsor_admin_*: authenticated, and each one checks has_role(auth.uid(), 'admin') itself.
--   * sponsor_service_*: service role only (the edge function's image and founder-photo paths).
--
-- THE SWITCH: 'sponsor_25days', created OFF. A public page has signed-out visitors, and the stock
-- feature_enabled_for() is false for anyone signed out, so this feature asks sponsor_25days_on_for(user):
-- audience 'everyone' -> anyone (signed out included); 'testers' -> admins and test accounts; 'off' -> nobody.
-- Every function below refuses (or answers on=false) while it is off for the caller.
--
-- Replay-safe: IF NOT EXISTS, CREATE OR REPLACE, ON CONFLICT DO NOTHING, DROP ... IF EXISTS; grants restated by
-- role name.

INSERT INTO public.feature_switches (key, audience, description)
VALUES ('sponsor_25days', 'off',
        '25 Days of Louisiana Giveaways: the public /sponsor page, /25days/rules, sign-ups and /admin/sponsors')
ON CONFLICT (key) DO NOTHING;

-- ── The switch decision for a public page ─────────────────────────────────
CREATE OR REPLACE FUNCTION public.sponsor_25days_on_for(p_user_id uuid)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
  SELECT COALESCE((SELECT s.audience = 'everyone' FROM public.feature_switches s WHERE s.key = 'sponsor_25days'), false)
      OR public.feature_enabled_for_user('sponsor_25days', p_user_id);
$function$;
REVOKE ALL ON FUNCTION public.sponsor_25days_on_for(uuid) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.sponsor_25days_on_for(uuid) TO service_role;
COMMENT ON FUNCTION public.sponsor_25days_on_for(uuid) IS
  'Is the 25 Days sponsor page on for this visitor (null = signed out)? everyone -> anyone; testers -> admins and '
  'test accounts; off -> nobody. Service role only (the sponsor-25days function); SQL callers use auth.uid().';

-- ── Tables ─────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.sponsor_invites (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  brand text NOT NULL CHECK (length(btrim(brand)) BETWEEN 1 AND 120),
  email text CHECK (email IS NULL OR length(email) <= 254),
  ref_code text NOT NULL UNIQUE CHECK (ref_code ~ '^[a-z0-9](?:[a-z0-9-]{0,62}[a-z0-9])?$'),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.sponsor_visits (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- NULL = a visit with no ?ref= (or one that is not a valid code): "direct".
  ref_code text CHECK (ref_code IS NULL OR ref_code ~ '^[a-z0-9](?:[a-z0-9-]{0,62}[a-z0-9])?$'),
  visited_at timestamptz NOT NULL DEFAULT now(),
  -- The referring site's origin only (the page strips path and query).
  referrer text CHECK (referrer IS NULL OR (length(referrer) <= 200 AND referrer ~ '^https?://')),
  device text NOT NULL DEFAULT 'unknown' CHECK (device IN ('phone', 'tablet', 'desktop', 'unknown'))
);
CREATE INDEX IF NOT EXISTS sponsor_visits_ref_idx ON public.sponsor_visits (ref_code, visited_at);

CREATE TABLE IF NOT EXISTS public.sponsor_signups (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  brand_name text NOT NULL CHECK (length(btrim(brand_name)) BETWEEN 1 AND 120),
  contact_name text NOT NULL CHECK (length(btrim(contact_name)) BETWEEN 1 AND 100),
  email text NOT NULL CHECK (length(email) BETWEEN 3 AND 254 AND email !~ '\s' AND email LIKE '%_@_%.__%'),
  phone text CHECK (phone IS NULL OR length(phone) <= 40),
  website text CHECK (website IS NULL OR (length(website) <= 300 AND website ~ '^https?://')),
  instagram text CHECK (instagram IS NULL OR length(instagram) <= 100),
  facebook text CHECK (facebook IS NULL OR length(facebook) <= 100),
  tiktok text CHECK (tiktok IS NULL OR length(tiktok) <= 100),
  prize_description text NOT NULL CHECK (length(btrim(prize_description)) BETWEEN 1 AND 1000),
  prize_value integer NOT NULL CHECK (prize_value BETWEEN 1 AND 100000),
  ship_to text CHECK (ship_to IS NULL OR ship_to IN ('winner', 'helpr')),
  notes text CHECK (notes IS NULL OR length(notes) <= 2000),
  any_day boolean NOT NULL DEFAULT false,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'confirmed', 'prize_received', 'posted')),
  -- wall_ok: the sponsor's own "OK to show our logo" tick. show_on_wall: the admin's toggle, never without it.
  wall_ok boolean NOT NULL DEFAULT false,
  show_on_wall boolean NOT NULL DEFAULT false,
  logo_path text CHECK (logo_path IS NULL OR logo_path ~ '^signups/[0-9a-f-]{36}\.(png|jpg|svg)$'),
  ref_code text CHECK (ref_code IS NULL OR ref_code ~ '^[a-z0-9](?:[a-z0-9-]{0,62}[a-z0-9])?$'),
  source text NOT NULL DEFAULT 'form' CHECK (source IN ('form', 'admin')),
  CONSTRAINT sponsor_signups_wall_needs_ok CHECK (NOT show_on_wall OR wall_ok)
);

