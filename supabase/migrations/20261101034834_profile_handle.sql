-- LEAD-PROFILE-LINK step 1 (owner 2026-10-31 ~10:50 PM, pop-up, OWNER-DECISIONS
-- "Shareable profile link"): every member gets ONE shareable link,
-- louisianahelpr.com/u/<handle>. This migration adds only the HANDLE; the
-- public read RPC and the page come in later steps.
--
-- THE HANDLE
--   * profiles.handle: lowercase letters, digits and single hyphens, 3 to 30
--     characters, starting and ending with a letter or digit; unique.
--   * profiles.handle_changed_at: set when the member picks their own handle.
--     Editable ONCE (the lead's spec: "unique, editable once in Settings").
--   * Generated by default, lazily: rpc_ensure_my_handle() gives the caller a
--     handle the first time they need one (Share my profile, Settings), from
--     the name the app already shows publicly ("Eli B." -> "eli-b", then
--     "eli-b-2", ...). No mass backfill: an UPDATE over every profiles row
--     would fire every profiles trigger (updated_at, contact-leak, ban locks)
--     on prod for nothing; a member with no handle simply has no link yet.
--   * SERVER-OWNED: a member cannot write handle or handle_changed_at on their
--     own row through the table API (trg_profile_handle_server_owned); only
--     the two RPCs below (transaction-local flag) or the server.
--   * rpc_set_my_handle(p_handle): normalises (trim, lowercase), refuses a bad
--     format (handle_invalid), a reserved word that would read as the app's own
--     page (handle_reserved), 7 or more digits, which could be a phone number
--     (handle_has_contact: the profile never shows contact info), one already
--     taken (handle_taken), and a second change (handle_already_changed).
--
-- REPLAY-SAFE: ADD COLUMN IF NOT EXISTS; constraint and index guarded;
-- CREATE OR REPLACE; DROP TRIGGER IF EXISTS before CREATE; grants restated.
-- Proof: src/test/pglite/profileHandle.pglite.mjs (--before is red).

ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS handle text;
ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS handle_changed_at timestamptz;

ALTER TABLE public.profiles DROP CONSTRAINT IF EXISTS profiles_handle_format;
ALTER TABLE public.profiles ADD CONSTRAINT profiles_handle_format
  CHECK (handle IS NULL OR (handle ~ '^[a-z0-9](?:[a-z0-9]|-(?=[a-z0-9])){2,29}$' AND length(handle) BETWEEN 3 AND 30));

CREATE UNIQUE INDEX IF NOT EXISTS profiles_handle_key ON public.profiles (handle) WHERE handle IS NOT NULL;

-- The slug of a display name (profiles.full_name): "Eli Broussard" -> "eli-b",
-- the first word and the last word's initial, as the app shows names publicly
-- ("Eli B."). Pure; never NULL; "member" when the name gives fewer than 3.
CREATE OR REPLACE FUNCTION public.profile_handle_base(p_full_name text)
RETURNS text
LANGUAGE sql
IMMUTABLE
SET search_path TO 'public'
AS $function$
  SELECT CASE WHEN length(b) >= 3 THEN b ELSE 'member' END
    FROM (
      SELECT left(lower(f), 24) || CASE WHEN l <> '' AND cardinality(w) > 1 THEN '-' || lower(left(l, 1)) ELSE '' END AS b
        FROM (
          SELECT w,
                 regexp_replace(coalesce(w[1], ''), '[^A-Za-z0-9]+', '', 'g') AS f,
                 regexp_replace(coalesce(w[cardinality(w)], ''), '[^A-Za-z0-9]+', '', 'g') AS l
            FROM (SELECT regexp_split_to_array(btrim(coalesce(p_full_name, '')), '\s+') AS w) a
        ) b
    ) c
$function$;

REVOKE ALL ON FUNCTION public.profile_handle_base(text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.profile_handle_base(text) TO authenticated, service_role;

-- Members never write the handle columns themselves.
CREATE OR REPLACE FUNCTION public.enforce_profile_handle_server_owned()
RETURNS trigger
LANGUAGE plpgsql
SET search_path TO 'public'
AS $function$
BEGIN
  IF (NEW.handle IS DISTINCT FROM OLD.handle OR NEW.handle_changed_at IS DISTINCT FROM OLD.handle_changed_at)
     AND coalesce(current_setting('app.profile_handle_rpc', true), '') <> '1'
     AND NOT public.is_server_context() THEN
    RAISE EXCEPTION 'handle_server_owned' USING ERRCODE = '42501',
      HINT = 'Change your profile link in Settings.';
  END IF;
  RETURN NEW;
END;
$function$;

REVOKE ALL ON FUNCTION public.enforce_profile_handle_server_owned() FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS trg_profile_handle_server_owned ON public.profiles;
CREATE TRIGGER trg_profile_handle_server_owned
  BEFORE UPDATE OF handle, handle_changed_at ON public.profiles
  FOR EACH ROW EXECUTE FUNCTION public.enforce_profile_handle_server_owned();

CREATE OR REPLACE FUNCTION public.enforce_profile_handle_insert_server_owned()
RETURNS trigger
LANGUAGE plpgsql
SET search_path TO 'public'
AS $function$
BEGIN
  IF (NEW.handle IS NOT NULL OR NEW.handle_changed_at IS NOT NULL)
     AND coalesce(current_setting('app.profile_handle_rpc', true), '') <> '1'
     AND NOT public.is_server_context() THEN
    RAISE EXCEPTION 'handle_server_owned' USING ERRCODE = '42501',
      HINT = 'Change your profile link in Settings.';
  END IF;
  RETURN NEW;
END;
$function$;

REVOKE ALL ON FUNCTION public.enforce_profile_handle_insert_server_owned() FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS trg_profile_handle_insert_server_owned ON public.profiles;
CREATE TRIGGER trg_profile_handle_insert_server_owned
  BEFORE INSERT ON public.profiles
  FOR EACH ROW EXECUTE FUNCTION public.enforce_profile_handle_insert_server_owned();

-- The caller's handle, made from their name the first time it is needed.
CREATE OR REPLACE FUNCTION public.rpc_ensure_my_handle()
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_uid uuid := auth.uid();
  v_row record;
  v_base text;
  v_try text;
  v_n int := 1;
BEGIN
  IF v_uid IS NULL THEN
    RAISE EXCEPTION 'not_authenticated' USING ERRCODE = '42501';
  END IF;
  SELECT p.user_id, p.handle, p.full_name INTO v_row
    FROM public.profiles p WHERE p.user_id = v_uid FOR UPDATE;
  IF v_row.user_id IS NULL THEN
    RAISE EXCEPTION 'profile_not_found';
  END IF;
  IF v_row.handle IS NOT NULL THEN
    RETURN v_row.handle;
  END IF;

  v_base := public.profile_handle_base(v_row.full_name);
  v_try := v_base;
  PERFORM set_config('app.profile_handle_rpc', '1', true);
  LOOP
    BEGIN
      UPDATE public.profiles SET handle = v_try WHERE user_id = v_uid;
      EXIT;
    EXCEPTION WHEN unique_violation THEN
      v_n := v_n + 1;
      IF v_n > 500 THEN
        v_try := v_base || '-' || substr(md5(v_uid::text || clock_timestamp()::text), 1, 6);
      ELSE
        v_try := v_base || '-' || v_n::text;
      END IF;
    END;
  END LOOP;
  PERFORM set_config('app.profile_handle_rpc', '0', true);
  RETURN v_try;
END;
$function$;

REVOKE ALL ON FUNCTION public.rpc_ensure_my_handle() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.rpc_ensure_my_handle() TO authenticated, service_role;

-- The member picks their own handle, once.
CREATE OR REPLACE FUNCTION public.rpc_set_my_handle(p_handle text)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_uid uuid := auth.uid();
  v_new text := lower(btrim(coalesce(p_handle, '')));
  v_row record;
BEGIN
  IF v_uid IS NULL THEN
    RAISE EXCEPTION 'not_authenticated' USING ERRCODE = '42501';
  END IF;
  IF v_new !~ '^[a-z0-9](?:[a-z0-9]|-(?=[a-z0-9])){2,29}$' OR length(v_new) NOT BETWEEN 3 AND 30 THEN
    RAISE EXCEPTION 'handle_invalid'
      USING HINT = 'Use 3 to 30 letters, numbers or single hyphens.';
  END IF;
  IF v_new = ANY (ARRAY['admin', 'administrator', 'support', 'help', 'helpr', 'helprs', 'louisianahelpr',
                        'settings', 'profile', 'jobs', 'job', 'declutter', 'messages', 'account', 'login',
                        'signup', 'sign-up', 'official', 'team', 'staff', 'moderator', 'security', 'api',
                        'null', 'undefined', 'me', 'you', 'user', 'users', 'member', 'members'])
     OR v_new LIKE 'louisianahelpr%' OR v_new LIKE 'admin%' THEN
    RAISE EXCEPTION 'handle_reserved'
      USING HINT = 'That link is reserved. Try another.';
  END IF;
  IF v_new ~ '[0-9]{7,}' OR length(regexp_replace(v_new, '[^0-9]', '', 'g')) >= 7 THEN
    RAISE EXCEPTION 'handle_has_contact'
      USING HINT = 'Leave phone numbers out of your link.';
  END IF;

  SELECT p.user_id, p.handle, p.handle_changed_at INTO v_row
    FROM public.profiles p WHERE p.user_id = v_uid FOR UPDATE;
  IF v_row.user_id IS NULL THEN
    RAISE EXCEPTION 'profile_not_found';
  END IF;
  IF v_row.handle = v_new THEN
    RETURN v_new;
  END IF;
  IF v_row.handle_changed_at IS NOT NULL THEN
    RAISE EXCEPTION 'handle_already_changed'
      USING HINT = 'You can change your profile link once, and you already have.';
  END IF;

  PERFORM set_config('app.profile_handle_rpc', '1', true);
  BEGIN
    UPDATE public.profiles
       SET handle = v_new, handle_changed_at = now()
     WHERE user_id = v_uid;
  EXCEPTION WHEN unique_violation THEN
    PERFORM set_config('app.profile_handle_rpc', '0', true);
    RAISE EXCEPTION 'handle_taken' USING HINT = 'Someone already has that link. Try another.';
  END;
  PERFORM set_config('app.profile_handle_rpc', '0', true);
  RETURN v_new;
END;
$function$;

REVOKE ALL ON FUNCTION public.rpc_set_my_handle(text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.rpc_set_my_handle(text) TO authenticated, service_role;
